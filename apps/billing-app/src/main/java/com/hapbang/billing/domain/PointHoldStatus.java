package com.hapbang.billing.domain;

// 보류 HP의 잔여 처리 상태와 최종 반환·지급·혼합 처리 결과를 구분한다.
public enum PointHoldStatus {
    /** 최초 보류 그대로다. 반환·지급한 적이 없다 */
    HELD,
    /** 일부를 반환·지급했고 남은 보류가 있다. 계속 반환·지급할 수 있다 */
    PARTIALLY_PROCESSED,
    /** 남은 보류가 없고 지급 없이 반환으로만 끝났다. 더 처리할 수 없다 */
    RELEASED,
    /** 남은 보류가 없고 반환 없이 지급으로만 끝났다. 더 처리할 수 없다(지급 기능 구현 전) */
    PAID,
    /** 남은 보류가 없고 반환·지급 없이 확정 차감(PG 환불 완료·환전 송금 완료)으로만 끝났다. 더 처리할 수 없다 (#241) */
    CAPTURED,
    /** 남은 보류가 없고 반환·지급·확정 차감 중 두 가지 이상이 함께 있었다. 더 처리할 수 없다 */
    MIXED
}
