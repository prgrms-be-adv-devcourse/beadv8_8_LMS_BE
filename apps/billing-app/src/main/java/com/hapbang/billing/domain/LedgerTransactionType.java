package com.hapbang.billing.domain;

// 원장 항목의 발생 사유를 충전·보류·반환·지급·환불·환전·환전 수수료·역분개로 구분한다.
public enum LedgerTransactionType {
    /** 충전. 충전 HP 가용 잔액이 는다 */
    CHARGE,
    /** 보류. 같은 HP 종류 안에서 가용 → 보류로 옮긴다 */
    HOLD,
    /** 반환. 보류를 결제한 회원에게 되돌린다. 차감했던 HP 종류 그대로 보류 → 가용으로 옮긴다. 정상 업무 처리이며 정정(REVERSAL)이 아니다 */
    RELEASE,
    /** 지급. 보낸 쪽 보류 HP를 받는 쪽 수익 HP 가용 잔액으로 옮긴다. 수수료 없음 */
    PAYOUT,
    /** 환불. 충전 HP를 PG 취소로 현금화해 충전 HP 가용 잔액이 준다 */
    REFUND,
    /** 환전. 보류한 수익 HP를 수수료 공제 후 KRW로 송금해 보류 잔액이 준다 */
    EXCHANGE,
    /** 환전 수수료. 환전 송금이 성공하면 공제한 수수료를 플랫폼 지갑의 수수료 수입으로 기록한다. 환전 한 건에 한 번이다 (#336) */
    EXCHANGE_FEE,
    /** 역분개. 잘못 기록한 원장 항목을 반대 부호의 새 항목으로 정정한다. 원본 원장을 반드시 가리키며 원본은 수정·삭제하지 않는다 */
    REVERSAL
}
