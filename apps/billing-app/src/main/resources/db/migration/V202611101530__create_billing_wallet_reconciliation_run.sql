-- 잔액 대사 실행 기록 (#822, BD-146). 매일 잔액 대사(BD-139) 한 회차가 끝날 때 한 번 남기고 지우지 않는다.
-- 기동할 때 이 기록으로 대사 지표(결과별 지갑 수, 마지막 성공 시각)를 채우고, 다음 회차는 가장 최근 실행의 FAILED 지갑을 이월한다.
-- 1) 실행: 시작 시각은 대사 기준 시각(마지막 성공 시각 지표의 값), since_at은 대상 기준 시각이다.
--    상태 컬럼은 없다(끝난 실행만 남는다. 도중에 멈춘 실행은 기록이 없다)
CREATE TABLE billing.wallet_reconciliation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ NOT NULL,
    since_at TIMESTAMPTZ NOT NULL,
    matched_count INTEGER NOT NULL,
    mismatched_count INTEGER NOT NULL,
    failed_count INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_wallet_reconciliation_run PRIMARY KEY (id),
    CONSTRAINT ck_wallet_reconciliation_run_1 CHECK (matched_count >= 0 AND mismatched_count >= 0 AND failed_count >= 0)
);

-- 가장 최근 실행(기동 시 결과별 지갑 수·마지막 성공 시각, 이월 대상). 하루 1행이라 failed 0 조건은 이 인덱스를 거슬러 읽어 찾는다
CREATE INDEX idx_wallet_reconciliation_run_1 ON billing.wallet_reconciliation_run (started_at);

-- 2) 문제 지갑: 불일치·실패 지갑만 남긴다. 일치한 지갑과 버킷별 차이·오류 내용은 남기지 않는다(로그에만)
CREATE TABLE billing.wallet_reconciliation_run_wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id BIGINT NOT NULL,
    wallet_id BIGINT NOT NULL,
    result VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_wallet_reconciliation_run_wallet PRIMARY KEY (id),
    CONSTRAINT fk_wallet_reconciliation_run_wallet_run_id FOREIGN KEY (run_id)
        REFERENCES billing.wallet_reconciliation_run (id),
    CONSTRAINT ck_wallet_reconciliation_run_wallet_result CHECK (result IN ('MISMATCHED', 'FAILED')),
    -- 한 실행에서 지갑은 한 결과만 가진다(재시도로 끝난 지갑은 마지막 결과 하나)
    CONSTRAINT uk_wallet_reconciliation_run_wallet_run_id_wallet_id UNIQUE (run_id, wallet_id)
);

CREATE INDEX idx_wallet_reconciliation_run_wallet_1 ON billing.wallet_reconciliation_run_wallet (run_id, result);
