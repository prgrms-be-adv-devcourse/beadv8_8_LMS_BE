-- 가상 송금(Mock 은행) 처리 기록 (#288). 로컬·테스트에서만 켜지는 MockPayoutController가 쓰는 "은행 쪽" 기록이다.
-- 우리 쪽 환전 송금 이력(exchange_payout)과 책임이 다르다: 이 테이블은 Mock 은행이 지급 요청 ID(멱등키)별로 받은 요청과 결과를
-- 서버 재시작 뒤에도 같은 결과로 돌려주기 위한 저장소다. 실제 돈은 움직이지 않으며 환전·지갑·보류·원장과 연결(FK)하지 않는다.
-- 운영에서는 Mock이 꺼져 있어 행이 생기지 않는다.
CREATE TABLE billing.mock_payout_transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 송금 요청 쪽이 만든 고정 UUID. Idempotency-Key와 같은 값
    payout_request_id VARCHAR(64) NOT NULL,
    exchange_id BIGINT NOT NULL,
    -- 송금 금액(KRW) = 환전 예상 수령액(신청 금액 - 수수료)
    amount_krw BIGINT NOT NULL,
    bank_code VARCHAR(3) NOT NULL,
    -- 테스트 계좌번호 원문은 저장하지 않고 HMAC-SHA256(소문자 hex 64자)만 둔다. 같은 키 재요청의 계좌 비교용
    account_number_hash VARCHAR(64) NOT NULL,
    account_holder_name VARCHAR(50) NOT NULL,
    -- PROCESSING(접수, 결과 전), SUCCEEDED(가상 송금 성공), FAILED(가상 송금 확정 실패)
    status VARCHAR(255) NOT NULL,
    transaction_id VARCHAR(64),
    failure_code VARCHAR(64),
    requested_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_mock_payout_transfer PRIMARY KEY (id),
    CONSTRAINT uk_mock_payout_transfer_payout_request_id UNIQUE (payout_request_id),
    CONSTRAINT uk_mock_payout_transfer_transaction_id UNIQUE (transaction_id),
    CONSTRAINT ck_mock_payout_transfer_status CHECK (status IN ('PROCESSING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_mock_payout_transfer_1 CHECK (amount_krw > 0),
    -- 성공이면 거래 번호, 실패면 실패 코드, 끝났으면 완료 시각이 있다
    CONSTRAINT ck_mock_payout_transfer_2 CHECK (
        (status = 'PROCESSING' AND transaction_id IS NULL AND failure_code IS NULL AND completed_at IS NULL)
        OR (status = 'SUCCEEDED' AND transaction_id IS NOT NULL AND failure_code IS NULL AND completed_at IS NOT NULL)
        OR (status = 'FAILED' AND transaction_id IS NULL AND failure_code IS NOT NULL AND completed_at IS NOT NULL))
);
