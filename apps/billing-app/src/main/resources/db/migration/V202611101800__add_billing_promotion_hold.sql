-- 주문 항목 보류의 플랫폼 몫(프로모션 보류).
-- 구매자 보류(point_hold) 하나에 쿠폰마다 프로모션 보류 한 행을 둔다. 플랫폼 몫은 그 쿠폰의 예산 예약 남은 예산에서 프로모션 지갑
-- 보류 칸으로 옮긴다(원장 PROMOTION_HOLD: 예약 − / 보류 +). 반환하면 같은 예약으로 되돌린다(원장 PROMOTION_RESTORE: 보류 − / 예약 +).
-- 판매자 지급은 기존 PAYOUT(프로모션 보류 − / 판매자 수익 가용 +)이다.

-- 1) 원장: 거래 유형 PROMOTION_HOLD·PROMOTION_RESTORE. 둘 다 프로모션 HP의 예약·보류 칸만 바꾼다
ALTER TABLE billing.point_ledger DROP CONSTRAINT ck_point_ledger_transaction_type;
ALTER TABLE billing.point_ledger ADD CONSTRAINT ck_point_ledger_transaction_type
    CHECK (transaction_type IN ('CHARGE', 'HOLD', 'RELEASE', 'PAYOUT', 'REFUND', 'EXCHANGE', 'EXCHANGE_FEE', 'REVERSAL',
                                'PROMOTION_FUND', 'PROMOTION_WITHDRAW', 'BUDGET_RESERVE', 'BUDGET_RELEASE',
                                'PROMOTION_HOLD', 'PROMOTION_RESTORE'));
ALTER TABLE billing.point_ledger DROP CONSTRAINT ck_point_ledger_promotion_transaction;
ALTER TABLE billing.point_ledger ADD CONSTRAINT ck_point_ledger_promotion_transaction CHECK (
    transaction_type NOT IN ('PROMOTION_FUND', 'PROMOTION_WITHDRAW', 'BUDGET_RESERVE', 'BUDGET_RELEASE',
                             'PROMOTION_HOLD', 'PROMOTION_RESTORE')
    OR (transaction_type IN ('PROMOTION_FUND', 'PROMOTION_WITHDRAW')
        AND point_type = 'PROMOTION' AND balance_bucket = 'AVAILABLE')
    OR (transaction_type IN ('BUDGET_RESERVE', 'BUDGET_RELEASE')
        AND point_type = 'PROMOTION' AND balance_bucket IN ('AVAILABLE', 'RESERVED'))
    OR (transaction_type IN ('PROMOTION_HOLD', 'PROMOTION_RESTORE')
        AND point_type = 'PROMOTION' AND balance_bucket IN ('RESERVED', 'HELD'))
);

-- 2) 프로모션 보류: 주문 항목(구매자 보류) × 쿠폰 한 행. 쿠폰 하나는 한 보류에 한 번만 붙는다.
--    상태: HELD(보류 중) → PAID(판매자에게 지급) 또는 RESTORED(예약으로 되돌림). 금액은 0보다 크다(0 HP 원장을 만들지 않는다)
CREATE TABLE billing.promotion_hold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    point_hold_id BIGINT NOT NULL,
    budget_reservation_id BIGINT NOT NULL,
    coupon_id BIGINT NOT NULL,
    member_coupon_id BIGINT NOT NULL,
    generation BIGINT NOT NULL,
    amount_hp BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_promotion_hold PRIMARY KEY (id),
    CONSTRAINT uk_promotion_hold_point_hold_id_coupon_id UNIQUE (point_hold_id, coupon_id),
    CONSTRAINT fk_promotion_hold_point_hold_id FOREIGN KEY (point_hold_id) REFERENCES billing.point_hold (id),
    CONSTRAINT fk_promotion_hold_budget_reservation_id FOREIGN KEY (budget_reservation_id)
        REFERENCES billing.budget_reservation (id),
    CONSTRAINT ck_promotion_hold_1 CHECK (amount_hp > 0),
    CONSTRAINT ck_promotion_hold_2 CHECK (generation >= 0),
    CONSTRAINT ck_promotion_hold_status CHECK (status IN ('HELD', 'PAID', 'RESTORED'))
);

-- 예약 하나의 프로모션 보류(대사: 보류 중 합 = 예약의 보류 중)
CREATE INDEX idx_promotion_hold_1 ON billing.promotion_hold (budget_reservation_id, status);

-- 프로모션만 보류한 0원 앵커도 반환 요청 ID를 보관한다(0 HP 상세·원장은 만들지 않는다).
ALTER TABLE billing.promotion_hold ADD COLUMN restoration_request_id VARCHAR(200);
ALTER TABLE billing.promotion_hold ADD CONSTRAINT ck_promotion_hold_restoration
    CHECK ((status = 'RESTORED' AND restoration_request_id IS NOT NULL)
        OR (status <> 'RESTORED' AND restoration_request_id IS NULL));

-- 기존 지급 건은 구매자 재원만 있다. 과거 금액과 원장에는 손대지 않고 재원 칸을 채운다.
ALTER TABLE billing.settlement ADD COLUMN buyer_paid_hp BIGINT;
-- 롤링 배포 중 이전 앱의 INSERT도 구매자 재원으로 채운다. 신규 앱은 두 재원을 명시한다.
CREATE FUNCTION billing.fill_settlement_buyer_funding() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.buyer_paid_hp IS NULL THEN
        NEW.buyer_paid_hp := NEW.gross_amount_hp;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER fill_settlement_buyer_funding BEFORE INSERT ON billing.settlement
    FOR EACH ROW EXECUTE FUNCTION billing.fill_settlement_buyer_funding();
ALTER TABLE billing.settlement ADD COLUMN promotion_paid_hp BIGINT NOT NULL DEFAULT 0;
UPDATE billing.settlement SET buyer_paid_hp = gross_amount_hp;
ALTER TABLE billing.settlement ALTER COLUMN buyer_paid_hp SET NOT NULL;
ALTER TABLE billing.settlement ADD CONSTRAINT ck_settlement_funding
    CHECK (buyer_paid_hp >= 0 AND promotion_paid_hp >= 0
        AND buyer_paid_hp::numeric + promotion_paid_hp = gross_amount_hp::numeric);

ALTER TABLE billing.hold_void ADD COLUMN promotion_restored_hp BIGINT NOT NULL DEFAULT 0;
ALTER TABLE billing.hold_void DROP CONSTRAINT ck_hold_void_1;
ALTER TABLE billing.hold_void ADD CONSTRAINT ck_hold_void_1 CHECK (
    released_hp >= 0 AND promotion_restored_hp >= 0
    AND ((outcome = 'RELEASED' AND (released_hp > 0 OR promotion_restored_hp > 0))
        OR (outcome <> 'RELEASED' AND released_hp = 0 AND promotion_restored_hp = 0))
);
