-- 보류 무효화 기록 (#479, docs/billing/CONTEXT.md 6장).
-- 호출한 모듈(강의·출연)이 참조 대상의 보류를 더는 쓰지 않는다고 알린 기록이다. 참조 대상당 한 건이며, 이 기록이 있는 참조 대상에는
-- 보류를 만들지 않는다(HOLD_VOIDED). 결과는 RELEASED(남은 보류 반환)·ALREADY_CLOSED(이미 끝난 보류)·VOIDED(보류 없음)다.
-- 보류 테이블과 불변식은 바꾸지 않는다. 반환한 HP는 반환 상세·원장(RELEASE)에 따로 남고, 여기에는 응답 재사용용 금액만 둔다.
CREATE TABLE billing.hold_void (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT NOT NULL,
    wallet_id BIGINT NOT NULL,
    reference_type VARCHAR(255) NOT NULL,
    reference_id BIGINT NOT NULL,
    outcome VARCHAR(255) NOT NULL,
    released_hp BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_hold_void PRIMARY KEY (id),
    CONSTRAINT uk_hold_void_reference UNIQUE (reference_type, reference_id),
    CONSTRAINT ck_hold_void_reference_type CHECK (reference_type IN ('LECTURE_ORDER', 'LECTURE_ORDER_ITEM', 'APPEARANCE_REQUEST', 'APPEARANCE_RECRUIT', 'RECRUIT_APPEARANCE', 'POINT_CHARGE', 'POINT_REFUND_REQUEST', 'EXCHANGE', 'SETTLEMENT')),
    CONSTRAINT ck_hold_void_outcome CHECK (outcome IN ('RELEASED', 'ALREADY_CLOSED', 'VOIDED')),
    -- 반환한 금액은 RELEASED일 때만 0보다 크다
    CONSTRAINT ck_hold_void_1 CHECK ((outcome = 'RELEASED' AND released_hp > 0) OR (outcome <> 'RELEASED' AND released_hp = 0))
);

-- 같은 지갑의 무효화 기록 조회
CREATE INDEX idx_hold_void_1 ON billing.hold_void (wallet_id);
