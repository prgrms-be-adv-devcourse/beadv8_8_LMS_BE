-- 메시지·시스템 안내 전달 outbox. 메시지 저장과 같은 트랜잭션에 쓰고, relay가 전달 Stream에 적재한다.
-- 수신자는 메시지 저장 때 확정한 불변 수신자 집합(recipient_set_id)으로 고정한다. 집합 테이블과의 FK는 다음 마이그레이션에서 건다.
create table chats.chat_outbox
(
    id               BIGINT generated by default as identity not null,
    delivery_id      UUID                                    not null,
    delivery_type    VARCHAR(20)                             not null,
    message_id       BIGINT                                  not null,
    chat_room_id     BIGINT                                  not null,
    room_sequence    BIGINT                                  not null,
    recipient_set_id BIGINT                                  not null,
    notify_rule      VARCHAR(40)                             not null,
    schema_version   INTEGER                                 not null,
    status           VARCHAR(20)                             not null,
    attempt_count    INTEGER                                 not null,
    next_attempt_at  TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    claim_token      UUID,
    lease_until      TIMESTAMP(6) WITHOUT TIME ZONE,
    stream_entry_id  VARCHAR(64),
    enqueued_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    requeue_count    INTEGER                                 not null,
    last_requeued_at TIMESTAMP(6) WITHOUT TIME ZONE,
    last_error       VARCHAR(1000),
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_outbox primary key (id),
    constraint uk_chat_outbox_delivery_id unique (delivery_id),
    constraint fk_chat_outbox_on_chat_message foreign key (message_id) references chats.chat_message (id),
    constraint fk_chat_outbox_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);

-- relay의 실행 대상·만료 처리권 선점, Redis 유실 재구성 대조
create index idx_chat_outbox_pending on chats.chat_outbox (next_attempt_at) where status = 'PENDING';
create index idx_chat_outbox_processing on chats.chat_outbox (lease_until) where status = 'PROCESSING';
create index idx_chat_outbox_enqueued on chats.chat_outbox (id) where status = 'ENQUEUED';

-- Redis 유실 재구성은 아직 발행하지 않은 체크포인트에서 시작한다. 완료(PUBLISHED·DEAD) 행은 훑지 않는다.
create index idx_chat_publish_checkpoint_pending on chats.chat_publish_checkpoint (consumer_group, id)
    where status = 'PENDING';
