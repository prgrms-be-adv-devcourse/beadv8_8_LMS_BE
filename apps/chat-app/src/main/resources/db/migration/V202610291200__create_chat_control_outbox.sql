-- 연결 제어 outbox. 회원 반영과 같은 트랜잭션에 기록하고, relay가 제어 Stream에 적재한다.
-- 같은 (회원, 원본 버전, 종류)는 한 번만 기록한다. 버전 없는 회원 정보(null)도 하나로 본다.
create table chats.chat_control_outbox
(
    id               BIGINT generated by default as identity not null,
    control_id       UUID                                    not null,
    control_type     VARCHAR(40)                             not null,
    user_id          BIGINT                                  not null,
    member_version   BIGINT,
    reason           VARCHAR(40)                             not null,
    schema_version   INTEGER                                 not null,
    status           VARCHAR(20)                             not null,
    attempt_count    INTEGER                                 not null,
    next_attempt_at  TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    claim_token      UUID,
    lease_until      TIMESTAMP(6) WITHOUT TIME ZONE,
    stream_entry_id  VARCHAR(64),
    enqueued_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    requeue_count    INTEGER                                 not null,
    last_requeued_at TIMESTAMP(6) WITHOUT TIME ZONE,
    last_error       VARCHAR(1000),
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_control_outbox primary key (id),
    constraint uk_chat_control_outbox_control_id unique (control_id),
    constraint uk_chat_control_outbox_user_version_type unique nulls not distinct (user_id, member_version, control_type)
);

-- relay의 실행 대상·만료 처리권 선점, Redis 유실 재구성 대조
create index idx_chat_control_outbox_pending on chats.chat_control_outbox (next_attempt_at) where status = 'PENDING';
create index idx_chat_control_outbox_processing on chats.chat_control_outbox (lease_until) where status = 'PROCESSING';
create index idx_chat_control_outbox_enqueued on chats.chat_control_outbox (id) where status = 'ENQUEUED';

-- consumer group별 Pub/Sub 발행 체크포인트. job_id는 deliveryId 또는 controlId다.
-- 사용자별 수신 이력이 아니다. outbox 행과 같은 트랜잭션에 PENDING으로 만든다.
create table chats.chat_publish_checkpoint
(
    id                    BIGINT generated by default as identity not null,
    consumer_group        VARCHAR(64)                             not null,
    job_id                UUID                                    not null,
    status                VARCHAR(20)                             not null,
    generation            INTEGER                                 not null,
    attempt_count         INTEGER                                 not null,
    next_attempt_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    last_error            VARCHAR(1000),
    published_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    last_subscriber_count BIGINT,
    dead_reason           VARCHAR(40),
    dead_stream_entry_id  VARCHAR(64),
    dead_at               TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at            TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at            TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_publish_checkpoint primary key (id),
    constraint uk_chat_publish_checkpoint_group_job unique (consumer_group, job_id)
);
