CREATE SCHEMA IF NOT EXISTS chats;

-- 회원 이벤트로 복제한 회원 정보. id는 회원 ID를 그대로 쓴다(회원 테이블에 FK를 걸지 않는다).
create table chats.chat_user
(
    id         BIGINT                         not null,
    nickname   VARCHAR(255)                   not null,
    role       VARCHAR(255)                   not null,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE not null,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE not null,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_chat_user primary key (id)
);

-- 1:1 채팅방. direct_key는 종료되지 않은 방에만 값이 있어 같은 두 회원의 활성 방을 하나로 제한한다.
create table chats.chat_room
(
    id            BIGINT generated by default as identity not null,
    room_type     VARCHAR(255)                            not null,
    status        VARCHAR(255)                            not null,
    direct_key    VARCHAR(255),
    last_sequence BIGINT                                  not null,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    ended_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    deleted_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_chat_room primary key (id),
    constraint uk_chat_room_direct_key unique (direct_key)
);

-- 참여자. 방·회원당 한 행이며 재입장하면 같은 행을 갱신한다.
create table chats.chat_room_member
(
    id                    BIGINT generated by default as identity not null,
    chat_room_id          BIGINT                                  not null,
    user_id               BIGINT                                  not null,
    joined_at             TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    left_at               TIMESTAMP(6) WITHOUT TIME ZONE,
    visible_from_sequence BIGINT                                  not null,
    participation_version INTEGER                                 not null,
    deleted_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_chat_room_member primary key (id),
    constraint uk_chat_room_member_room_user unique (chat_room_id, user_id),
    constraint fk_chat_room_member_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);

-- 내 채팅방 목록 조회(user_id, 참여 중 여부)
create index idx_chat_room_member_user_id_left_at on chats.chat_room_member (user_id, left_at);

-- 메시지. room_sequence는 방 안에서 겹치지 않는 순번이다.
create table chats.chat_message
(
    id             BIGINT generated by default as identity not null,
    chat_room_id   BIGINT                                  not null,
    room_sequence  BIGINT                                  not null,
    sender_user_id BIGINT                                  not null,
    message_type   VARCHAR(255)                            not null,
    content        TEXT                                    not null,
    sent_at        TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_chat_message primary key (id),
    constraint uk_chat_message_room_sequence unique (chat_room_id, room_sequence),
    constraint fk_chat_message_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);

-- 방 생성·입장·퇴장·재입장·종료 기록. INSERT만 한다.
create table chats.chat_room_log
(
    id            BIGINT generated by default as identity not null,
    chat_room_id  BIGINT                                  not null,
    actor_user_id BIGINT                                  not null,
    event_type    VARCHAR(255)                            not null,
    occurred_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_room_log primary key (id),
    constraint fk_chat_room_log_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);

create index idx_chat_room_log_chat_room_id on chats.chat_room_log (chat_room_id);
