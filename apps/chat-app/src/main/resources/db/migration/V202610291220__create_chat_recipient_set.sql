-- 불변 수신자 집합. 참여 변경(생성·퇴장·재입장) 때 방 잠금 아래 새 버전을 만들고, 메시지 전달 작업은 그 버전만 참조한다.
-- 만든 버전의 항목은 고치지 않는다.
create table chats.chat_recipient_set
(
    id           BIGINT generated by default as identity not null,
    chat_room_id BIGINT                                  not null,
    set_version  INTEGER                                 not null,
    member_count INTEGER                                 not null,
    created_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_recipient_set primary key (id),
    constraint uk_chat_recipient_set_room_version unique (chat_room_id, set_version),
    constraint fk_chat_recipient_set_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);

-- 집합 항목. 그 버전을 만들 때의 활성 참여자와 참여 세대
create table chats.chat_recipient_set_member
(
    recipient_set_id      BIGINT  not null,
    user_id               BIGINT  not null,
    participation_version INTEGER not null,
    constraint pk_chat_recipient_set_member primary key (recipient_set_id, user_id),
    constraint fk_chat_recipient_set_member_on_set foreign key (recipient_set_id)
        references chats.chat_recipient_set (id)
);

alter table chats.chat_outbox
    add constraint fk_chat_outbox_on_chat_recipient_set foreign key (recipient_set_id)
        references chats.chat_recipient_set (id);

-- 방의 현재 집합 버전과 활성 참여자 수. 참여 행과 같은 트랜잭션에서 함께 바꾼다
alter table chats.chat_room
    add column current_recipient_set_id BIGINT,
    add column active_member_count      INTEGER not null default 0,
    add constraint fk_chat_room_on_current_recipient_set foreign key (current_recipient_set_id)
        references chats.chat_recipient_set (id);

-- 기존 데이터: 종료되지 않은 방은 지금의 활성 참여로 첫 집합(버전 1)을 만든다. 집합이 없는 방은 전송 대상으로 열지 않는다
insert into chats.chat_recipient_set (chat_room_id, set_version, member_count, created_at)
select r.id,
       1,
       (select count(*)
        from chats.chat_room_member m
        where m.chat_room_id = r.id and m.left_at is null and m.deleted_at is null),
       localtimestamp
from chats.chat_room r
where r.status = 'ACTIVE' and r.deleted_at is null;

insert into chats.chat_recipient_set_member (recipient_set_id, user_id, participation_version)
select s.id, m.user_id, m.participation_version
from chats.chat_recipient_set s
         join chats.chat_room_member m
              on m.chat_room_id = s.chat_room_id and m.left_at is null and m.deleted_at is null
where s.set_version = 1;

update chats.chat_room r
set current_recipient_set_id = s.id
from chats.chat_recipient_set s
where s.chat_room_id = r.id and s.set_version = 1;

update chats.chat_room r
set active_member_count = (select count(*)
                           from chats.chat_room_member m
                           where m.chat_room_id = r.id and m.left_at is null and m.deleted_at is null);

alter table chats.chat_room
    alter column active_member_count drop default;
