-- 모집용 단체방(GROUP). 1:1 방과 같은 chat_room·참여·메시지·수신자 집합 테이블을 쓰고, 단체방 전용 값만 더한다.
-- 단체방 전용 컬럼은 1:1 방에서 null이다. 기존 행은 바꾸지 않는다(status_version은 0).
-- 모집글·호스트는 출연·회원 앱의 ID만 담는다(다른 앱 DB에 FK를 걸지 않는다).
alter table chats.chat_room
    add column recruit_id         BIGINT,
    add column owner_user_id      BIGINT,
    add column title              VARCHAR(255),
    add column max_guest_members  INTEGER,
    add column status_reason      VARCHAR(40),
    add column read_only_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    add column history_expires_at TIMESTAMP(6) WITHOUT TIME ZONE,
    add column status_version     INTEGER not null default 0,
    add constraint ck_chat_room_group_columns check (room_type <> 'GROUP'
        or (recruit_id is not null and owner_user_id is not null and title is not null
            and max_guest_members is not null));

-- 모집글마다 현재 방(사용 중·일시 중지)은 하나다. 읽기 전용(폐쇄·자격 상실)으로 남은 이전 방은 제외해 새 방과 공존한다.
-- 동시에 만들면 한쪽이 이 인덱스에 걸리고, 다시 시도해 먼저 만든 방을 돌려준다.
create unique index uk_chat_room_group_current on chats.chat_room (recruit_id)
    where room_type = 'GROUP' and status in ('ACTIVE', 'SUSPENDED');

-- 관리자 기록의 행위 대상(초대·강퇴된 회원). 대상이 행위자 자신이거나 없으면 null이다.
alter table chats.chat_room_log
    add column target_user_id BIGINT;

-- 단체방 초대 요청의 회원별 결과. 방·요청 ID마다 한 행이고, 보존 기간 안의 같은 요청 ID는 이 결과를 그대로 돌려준다.
-- 보존 기간이 지난 같은 요청 ID는 새 요청으로 처리하고 이 행을 새 결과로 바꾼다.
create table chats.chat_group_invite_request
(
    id                BIGINT generated by default as identity not null,
    chat_room_id      BIGINT                                  not null,
    request_id        UUID                                    not null,
    requester_user_id BIGINT                                  not null,
    results           JSONB                                   not null,
    recorded_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_group_invite_request primary key (id),
    constraint uk_chat_group_invite_request_room_request unique (chat_room_id, request_id),
    constraint fk_chat_group_invite_request_on_chat_room foreign key (chat_room_id) references chats.chat_room (id)
);
