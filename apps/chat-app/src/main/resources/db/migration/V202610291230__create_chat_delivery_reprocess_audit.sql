-- 전달·제어 작업의 운영 재처리 감사 기록. INSERT만 한다.
-- 재처리는 시도 횟수·격리 원인을 새 처리 세대에 맞춰 비우므로, 비우기 전 상태를 재처리마다 한 행으로 남긴다.
-- last_error 컬럼은 현재 오류만 담고, 이전 세대의 기록은 이 테이블에서 본다.
create table chats.chat_delivery_reprocess_audit
(
    id                             BIGINT generated by default as identity not null,
    job_stream                     VARCHAR(20)                             not null,
    consumer_group                 VARCHAR(64)                             not null,
    job_id                         UUID                                    not null,
    previous_generation            INTEGER,
    previous_publish_status        VARCHAR(20),
    previous_publish_attempt_count INTEGER,
    previous_dead_reason           VARCHAR(40),
    previous_dead_stream_entry_id  VARCHAR(64),
    previous_publish_error         VARCHAR(1000),
    previous_outbox_status         VARCHAR(20)                             not null,
    previous_enqueue_attempt_count INTEGER                                 not null,
    previous_requeue_count         INTEGER                                 not null,
    previous_stream_entry_id       VARCHAR(64),
    previous_enqueue_error         VARCHAR(1000),
    reprocessed_at                 TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_chat_delivery_reprocess_audit primary key (id)
);

create index idx_chat_delivery_reprocess_audit_job on chats.chat_delivery_reprocess_audit (consumer_group, job_id);

-- 재처리로 비우지 않는 누적 횟수. 연결 제어 기록(JdbcChatConnectionControl)은 이 컬럼을 넣지 않으므로 기본값 0을 둔다.
-- total_attempt_count: outbox는 누적 적재 시도, 체크포인트는 누적 발행 실패(구독자 0명·Redis 연결 불가·쓰기 거절은 세지 않는다).
-- total_requeue_count: 누적 재적재
alter table chats.chat_outbox
    add column total_attempt_count INTEGER not null default 0,
    add column total_requeue_count INTEGER not null default 0;

alter table chats.chat_control_outbox
    add column total_attempt_count INTEGER not null default 0,
    add column total_requeue_count INTEGER not null default 0;

alter table chats.chat_publish_checkpoint
    add column total_attempt_count INTEGER not null default 0;

-- 기존 행은 지금까지의 횟수로 시작한다
update chats.chat_outbox set total_attempt_count = attempt_count, total_requeue_count = requeue_count;
update chats.chat_control_outbox set total_attempt_count = attempt_count, total_requeue_count = requeue_count;
update chats.chat_publish_checkpoint set total_attempt_count = attempt_count;
