-- 회원 탈퇴 작업 기록 (#593). 탈퇴 한 번 시도마다 한 줄이다. 회원 앱이 탈퇴 확인을 지휘할 때 어디까지 했는지 남겨,
-- 중간에 실패하거나 앱이 죽어도 배치가 이어서 처리한다. id가 지갑 닫기·다시 열기 호출의 멱등 키(withdrawalId)다.
-- 회원 상태(users.status)와 별개다. 회원 상태는 탈퇴가 끝날 때(COMPLETED) 한 번만 WITHDRAWN으로 바뀐다
create table members.withdrawal
(
    id                 BIGINT generated by default as identity not null,
    user_id            BIGINT                                  not null,
    status             VARCHAR(255)                            not null,
    -- 막힌 이유 기록 (WithdrawalBlockReasonDto 목록 JSON). 막혀서 끝났을 때만 있다
    block_reasons      JSONB,
    attempts           INTEGER                                 not null,
    last_error         VARCHAR(1000),
    completed_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_withdrawal primary key (id),
    constraint ck_withdrawal_status check (status in
        ('CHECKING', 'WALLET_CLOSED', 'COMPLETED', 'BLOCKED', 'ROLLED_BACK', 'NEEDS_RECOVERY'))
);

alter table members.withdrawal
    add constraint FK_WITHDRAWAL_ON_USER foreign key (user_id) references members.users (id);

-- 회원 한 명에 진행 중인 탈퇴 작업은 하나만 (탈퇴를 두 번 눌러도 동시에 두 개가 돌지 않는다)
create unique index uk_withdrawal_user_in_progress on members.withdrawal (user_id)
    where status in ('CHECKING', 'WALLET_CLOSED', 'NEEDS_RECOVERY');
