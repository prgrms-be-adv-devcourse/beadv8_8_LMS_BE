create table members.influencer_upgrade_request
(
    id               BIGINT generated by default as identity not null,
    user_id          BIGINT                                  not null,
    status           VARCHAR(255)                            not null,
    request_reason   TEXT                                    not null,
    rejection_reason TEXT,
    reviewed_by      BIGINT,
    requested_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    reviewed_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_influencer_upgrade_request primary key (id)
);

alter table members.influencer_upgrade_request
    add constraint FK_INFLUENCER_UPGRADE_REQUEST_ON_USER foreign key (user_id) references members.users (id);

-- 회원당 심사 대기 신청은 1건만 (동시 신청도 DB가 막는다)
create unique index uk_influencer_upgrade_request_one_pending
    on members.influencer_upgrade_request (user_id)
    where status = 'PENDING';
