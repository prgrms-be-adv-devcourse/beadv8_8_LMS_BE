CREATE SCHEMA IF NOT EXISTS members;

create table members.users
(
    id                BIGINT generated by default as identity not null,
    nickname          VARCHAR(255),
    role              VARCHAR(255),
    status            VARCHAR(255),
    email             VARCHAR(255),
    profile_image_key VARCHAR(255),
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    deleted_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_users primary key (id),
    constraint uc_users_email unique (email)
);

create table members.oauth_account
(
    id               BIGINT generated by default as identity not null,
    user_id          BIGINT                                  not null,
    provider         VARCHAR(255)                            not null,
    provider_user_id VARCHAR(255)                            not null,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_oauth_account primary key (id),
    constraint uc_oauth_account_provider_provider_user_id unique (provider, provider_user_id)
);

alter table members.oauth_account
    add constraint FK_OAUTH_ACCOUNT_ON_USER foreign key (user_id) references members.users (id);
