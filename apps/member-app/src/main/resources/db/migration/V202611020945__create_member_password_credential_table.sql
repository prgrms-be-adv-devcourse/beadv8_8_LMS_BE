-- 이메일·비밀번호 로그인 정보 (#499). 구글 계정(oauth_account)처럼 로그인 수단을 회원(users)과 분리한다.
-- 비밀번호 원문이 아니라 해시만 저장한다. 구글 회원은 행이 없다
create table members.password_credential
(
    id                  BIGINT generated by default as identity not null,
    user_id             BIGINT                                  not null,
    password_hash       VARCHAR(255)                            not null,
    password_changed_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    created_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_password_credential primary key (id),
    constraint uc_password_credential_user_id unique (user_id)
);

alter table members.password_credential
    add constraint FK_PASSWORD_CREDENTIAL_ON_USER foreign key (user_id) references members.users (id);
