-- 회원 이벤트 처리 실패 기록 (#976). 회원 그룹이 재시도를 다 쓰고 DLT로 보내기 직전에 남긴다.
-- 관리자가 이유를 보고 수동으로 다시 처리한다. DLT 보존 기간(7일)과 상관없이 남는다.
CREATE TABLE chatbot.member_event_failure (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 이벤트의 회원 ID. 읽지 못한 메시지는 key(회원 ID)에서 읽고, 그것도 숫자가 아니면 비운다
    user_id          BIGINT,
    -- JOINED, MODIFIED, MASKED, UNREADABLE
    event_type       VARCHAR(20)   NOT NULL,
    -- 다시 처리할 수 있는지(읽지 못함·필수 값 없음이면 false)
    replayable       BOOLEAN       NOT NULL,
    -- 다시 처리할 이벤트 JSON. 다시 처리할 수 없거나 처리됐으면 비운다. 회원이 마스킹되면 닉네임·분야·자기소개를 비운다
    payload          TEXT,
    source_topic     VARCHAR(255)  NOT NULL,
    source_partition INTEGER       NOT NULL,
    source_offset    BIGINT        NOT NULL,
    -- 마지막 실패의 예외 클래스(리스너 감싸기를 벗긴 것)와 가장 안쪽 원인 클래스
    exception_class  VARCHAR(255)  NOT NULL,
    root_cause_class VARCHAR(255)  NOT NULL,
    -- 마지막 실패의 메시지. 이메일·전화를 지우고 200자로 자른다. DB 예외는 SQLState만
    message          VARCHAR(200),
    -- PENDING, RESOLVED
    status           VARCHAR(20)   NOT NULL,
    failed_at        TIMESTAMP(6)  NOT NULL,
    retry_count      INTEGER       NOT NULL DEFAULT 0,
    last_retried_at  TIMESTAMP(6),
    resolved_at      TIMESTAMP(6),
    -- 다시 처리해 성공시킨 관리자 회원 ID
    resolved_by      BIGINT,
    -- 같은 메시지를 두 번 적지 않는다(기록 뒤 DLT 전송이 실패해 다시 오는 경우)
    CONSTRAINT uk_member_event_failure_source UNIQUE (source_topic, source_partition, source_offset)
);

-- 관리자 목록(상태별 최신순)과 전체 재처리(PENDING 오래된 순)
CREATE INDEX idx_member_event_failure_status_id ON chatbot.member_event_failure (status, id);
-- 마스킹할 때 그 회원의 PENDING 원문 비우기
CREATE INDEX idx_member_event_failure_user_id ON chatbot.member_event_failure (user_id);
