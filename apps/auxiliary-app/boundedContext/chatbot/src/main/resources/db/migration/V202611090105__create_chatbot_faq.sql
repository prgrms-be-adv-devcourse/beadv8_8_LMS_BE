-- FAQ 챗봇의 FAQ 원본(#715). 시드 파일(chatbot/faq-seed.json)을 시작할 때 code로 맞춘다.
-- content_hash: 임베딩에 쓰는 내용(분류·질문·답변)의 SHA-256. indexed_hash: 마지막으로 색인에 성공한 내용의 해시.
-- 둘이 다르거나 indexed_hash가 null인 행만 다시 임베딩한다.
create table chatbot.faq
(
    id           BIGINT generated by default as identity not null,
    code         VARCHAR(20)                             not null,
    category     VARCHAR(30)                             not null,
    question     VARCHAR(200)                            not null,
    answer       VARCHAR(2000)                           not null,
    policy_ref   VARCHAR(300)                            not null,
    sort_order   INTEGER                                 not null,
    content_hash VARCHAR(64)                             not null,
    indexed_hash VARCHAR(64),
    indexed_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_faq primary key (id),
    constraint uk_faq_code unique (code)
);
