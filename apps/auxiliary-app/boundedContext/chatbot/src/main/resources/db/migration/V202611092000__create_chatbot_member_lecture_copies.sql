-- 챗봇 회원·강의 사본과 탈퇴 회원 처리 (#717). 규칙은 #716 사본과 같다(원본 DTO를 그대로 담고, 시각은 KST timestamp).

-- 회원 사본 (회원 UserDto). 닉네임은 저장하지 않는다(추천·LLM에 필요 없음). 해시는 받은 DTO 전체(닉네임 포함)로 계산한다.
-- 회원은 하드 삭제가 없어 원본 없음 표시를 하지 않는다
CREATE TABLE chatbot.member_copy (
    id         BIGINT       PRIMARY KEY,
    -- USER, INFLUENCER, VERIFIED_INFLUENCER, ADMIN
    role       VARCHAR(30)  NOT NULL,
    -- ACTIVE, SUSPENDED, WITHDRAWN
    status     VARCHAR(20)  NOT NULL,
    -- 콘텐츠 분야 코드 목록(회원이 고른 순서). 마스킹하면 비운다
    categories JSONB        NOT NULL DEFAULT '[]',
    -- 자기소개. 마스킹하면 비운다
    bio        TEXT,
    -- 회원 원본 version. UserDto 규칙상 비어 있을 수 있다(버전 도입 전 정보)
    version    BIGINT,
    dto_hash   CHAR(64)     NOT NULL,
    synced_at  TIMESTAMP(6) NOT NULL
);

-- 강의 사본 (강의 LectureSyncDto). onSale·deleted는 강의가 판단한 값을 그대로 담는다
CREATE TABLE chatbot.lecture_copy (
    id                BIGINT       PRIMARY KEY,
    seller_user_id    BIGINT       NOT NULL,
    title             TEXT         NOT NULL,
    description       TEXT,
    -- 삭제되지 않은 콘텐츠 제목, sequence 순. 콘텐츠 id·sequence는 해시에만 반영된다
    content_titles    JSONB        NOT NULL DEFAULT '[]',
    on_sale           BOOLEAN      NOT NULL,
    deleted           BOOLEAN      NOT NULL,
    version           BIGINT       NOT NULL,
    dto_hash          CHAR(64)     NOT NULL,
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_run_id       BIGINT,
    synced_at         TIMESTAMP(6) NOT NULL
);

-- 구매 = 주문 항목 사본 (강의 LecturePurchaseSyncDto). result는 강의가 줄인 값(OWNED, PENDING, CANCELED, RETURNED, FAILED)
CREATE TABLE chatbot.lecture_purchase_copy (
    order_item_id     BIGINT       PRIMARY KEY,
    buyer_user_id     BIGINT       NOT NULL,
    lecture_id        BIGINT       NOT NULL,
    result            VARCHAR(20)  NOT NULL,
    ordered_at        TIMESTAMP(6) NOT NULL,
    purchased_at      TIMESTAMP(6),
    version           BIGINT       NOT NULL,
    dto_hash          CHAR(64)     NOT NULL,
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_run_id       BIGINT,
    synced_at         TIMESTAMP(6) NOT NULL
);

-- 마스킹 삭제·회원별 조회
CREATE INDEX idx_lecture_purchase_copy_buyer ON chatbot.lecture_purchase_copy (buyer_user_id);

-- 장바구니 항목 사본 (강의 CartItemSyncDto)
CREATE TABLE chatbot.cart_item_copy (
    id                BIGINT       PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    lecture_id        BIGINT       NOT NULL,
    deleted           BOOLEAN      NOT NULL,
    added_at          TIMESTAMP(6) NOT NULL,
    version           BIGINT       NOT NULL,
    dto_hash          CHAR(64)     NOT NULL,
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_run_id       BIGINT,
    synced_at         TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_cart_item_copy_user ON chatbot.cart_item_copy (user_id);

-- 강의 리뷰 별점 사본 (강의 LectureReviewSyncDto). counted는 강의가 판단한 값을 그대로 담는다
CREATE TABLE chatbot.lecture_review_copy (
    id                BIGINT       PRIMARY KEY,
    lecture_id        BIGINT       NOT NULL,
    reviewer_user_id  BIGINT       NOT NULL,
    rating            INTEGER      NOT NULL,
    counted           BOOLEAN      NOT NULL,
    deleted           BOOLEAN      NOT NULL,
    version           BIGINT       NOT NULL,
    dto_hash          CHAR(64)     NOT NULL,
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_run_id       BIGINT,
    synced_at         TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_lecture_review_copy_reviewer ON chatbot.lecture_review_copy (reviewer_user_id);

-- 받은 출연 리뷰의 마스킹 삭제(#716 표)
CREATE INDEX idx_appearance_review_copy_reviewee ON chatbot.appearance_review_copy (reviewee_user_id);

-- 개인정보를 마스킹한 회원(UserMaskedEvent). 이 회원의 구매·장바구니·쓴 리뷰·받은 출연 리뷰·분야·자기소개는 다시 받지 않는다
CREATE TABLE chatbot.masked_member (
    user_id   BIGINT       PRIMARY KEY,
    masked_at TIMESTAMP(6) NOT NULL
);

-- ES 색인·삭제 요청. 데이터를 바꾸는 트랜잭션에 함께 적고 커밋 뒤 실행·재시도한다. 실행기는 추천 색인(#718·#719)이 더한다
CREATE TABLE chatbot.index_task (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 대상 index 종류(IndexType 이름): INFLUENCER(chatbot-influencers)
    index_type      VARCHAR(30)   NOT NULL,
    -- 문서 ID
    doc_id          VARCHAR(100)  NOT NULL,
    -- UPSERT, DELETE, PARTIAL
    action          VARCHAR(10)   NOT NULL,
    payload         JSONB,
    attempts        INTEGER       NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP(6)  NOT NULL,
    done_at         TIMESTAMP(6),
    created_at      TIMESTAMP(6)  NOT NULL
);

-- 실행기가 할 일을 시각 순으로 읽는다
CREATE INDEX idx_index_task_pending ON chatbot.index_task (next_attempt_at) WHERE done_at IS NULL;

