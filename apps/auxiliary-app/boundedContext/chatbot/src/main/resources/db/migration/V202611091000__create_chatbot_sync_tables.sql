-- 챗봇 동기화 기반 (#716). 다른 모듈 데이터의 읽기용 사본과 주간 싱크 실행 기록.
-- 사본은 원본이 준 DTO를 그대로 담는다(원본 규칙을 해석하지 않는다). 시각은 KST timestamp, 마이크로초까지.

-- 출연 사본 (출연 #713 AppearanceSyncDto). 이벤트와 싱크가 같은 행을 바꾸므로 반영은 version 비교를 넣은 upsert 한 문장으로 한다
CREATE TABLE chatbot.appearance_copy (
    id                BIGINT       PRIMARY KEY,
    host_id           BIGINT       NOT NULL,
    guest_id          BIGINT       NOT NULL,
    -- 원본의 공개 결과: SCHEDULED, COMPLETED, CANCELED, NO_SHOW
    result            VARCHAR(20)  NOT NULL,
    scheduled_at      TIMESTAMP(6) NOT NULL,
    version           BIGINT       NOT NULL,
    -- 받은 DTO의 SHA-256(hex). 싱크가 원본과 값을 비교한다
    dto_hash          CHAR(64)     NOT NULL,
    -- 끝까지 성공한 싱크에서 원본에 없던 행. 지우지 않고 추천에서만 뺀다
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 이 행을 마지막으로 본 싱크 회차
    seen_run_id       BIGINT,
    -- 이벤트·싱크로 마지막으로 받은 시각
    synced_at         TIMESTAMP(6) NOT NULL
);

-- 공개된 출연 리뷰 사본 (출연 AppearanceReviewSyncDto). 리뷰는 공개 뒤 바뀌지 않아 version이 없다
CREATE TABLE chatbot.appearance_review_copy (
    review_id         BIGINT       PRIMARY KEY,
    appearance_id     BIGINT       NOT NULL,
    reviewee_user_id  BIGINT       NOT NULL,
    rating            INTEGER      NOT NULL,
    dto_hash          CHAR(64)     NOT NULL,
    missing_in_source BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_run_id       BIGINT,
    synced_at         TIMESTAMP(6) NOT NULL
);

-- 싱크 회차. 종류마다 따로 실행·기록한다
CREATE TABLE chatbot.sync_run (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- APPEARANCE, APPEARANCE_REVIEW
    type           VARCHAR(30)   NOT NULL,
    -- SCHEDULED, RETRY, ADMIN
    trigger_type   VARCHAR(20)   NOT NULL,
    -- 관리자 실행이면 관리자 회원 ID
    requested_by   BIGINT,
    -- RUNNING, SUCCEEDED, FAILED, SKIPPED
    status         VARCHAR(20)   NOT NULL,
    started_at     TIMESTAMP(6)  NOT NULL,
    finished_at    TIMESTAMP(6),
    scanned        BIGINT        NOT NULL DEFAULT 0,
    inserted       BIGINT        NOT NULL DEFAULT 0,
    -- 원본이 새것이거나 같은 version인데 값이 달라 고친 건수 (version만 오른 정상 건은 넣지 않는다)
    fixed          BIGINT        NOT NULL DEFAULT 0,
    ours_newer     BIGINT        NOT NULL DEFAULT 0,
    marked_missing BIGINT        NOT NULL DEFAULT 0,
    warning        BOOLEAN       NOT NULL DEFAULT FALSE,
    error          VARCHAR(1000)
);

-- 회차 목록(종류별 최신순)과 오늘 성공 회차 확인(재시도)
CREATE INDEX idx_sync_run_type_started_at ON chatbot.sync_run (type, started_at DESC);

-- 회차의 어긋난 항목. 회차당 최대 N건, 종류마다 최근 M회만 남긴다(설정값)
CREATE TABLE chatbot.sync_mismatch (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT       NOT NULL REFERENCES chatbot.sync_run (id) ON DELETE CASCADE,
    type           VARCHAR(30)  NOT NULL,
    source_id      BIGINT       NOT NULL,
    -- ONLY_IN_SOURCE, SOURCE_NEWER, SAME_VERSION_DIFFERENT, OURS_NEWER, MISSING_IN_SOURCE
    kind           VARCHAR(30)  NOT NULL,
    our_version    BIGINT,
    source_version BIGINT
);

CREATE INDEX idx_sync_mismatch_run_id ON chatbot.sync_mismatch (run_id);
