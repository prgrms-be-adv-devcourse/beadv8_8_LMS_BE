-- 예약 알림(N10, ND-029·ND-034·ND-133~ND-144). 예약 알림을 보내기 전까지의 기록이다(ND-025의 넷 중 하나, 처음 쓰는 작업에서 만든다
-- ND-046). (종류, 대상 ID, 받는 사람)마다 한 행이고, 예약보다 먼저 온 취소도 "취소" 행으로 남겨 늦게 온 생성을 막는다(ND-034).
CREATE TABLE notification.notification_schedule
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 예약 알림 종류 코드(ND-137)
    kind              VARCHAR(100)                   NOT NULL,
    -- 대상 ID(요청서·모집글·출연·주문 항목 ID, 이벤트 계약 0.3). 발행 앱 테이블과 FK·JOIN하지 않는다
    target_id         BIGINT                         NOT NULL,
    -- 받는 사람(회원 ID)
    receiver_user_id  BIGINT                         NOT NULL,
    -- SCHEDULED(예약) → SENT(보냄)·CANCELED(취소)·SKIPPED(건너뜀). 끝 상태는 바뀌지 않는다
    status            VARCHAR(20)                    NOT NULL,
    -- 보낼 시각. 예약보다 먼저 온 취소 행은 모른다
    send_at           TIMESTAMP(6) WITH TIME ZONE,
    -- 업무 기한(ND-135). 행 정리 기준(ND-142). 취소가 먼저 온 구매 취소 마감 임박은 대체 기한(ND-143)
    business_deadline TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    -- 문구 값(제목·기한, ND-140). 예약보다 먼저 온 취소 행은 없다
    payload           JSONB,
    -- 끝 상태가 된 시각
    processed_at      TIMESTAMP(6) WITH TIME ZONE,
    -- 배치가 보내지 못한 횟수(ND-147). 실패한 저장 트랜잭션과 따로 기록하고, 3번이면 건너뜀으로 끝낸다
    failure_count     INTEGER                        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_notification_schedule PRIMARY KEY (id),
    CONSTRAINT uk_notification_schedule UNIQUE (kind, target_id, receiver_user_id),
    CONSTRAINT ck_notification_schedule_status CHECK (status IN ('SCHEDULED', 'SENT', 'CANCELED', 'SKIPPED')),
    -- 보낼 예약에는 보낼 시각과 문구 값이 있어야 한다
    CONSTRAINT ck_notification_schedule_sendable CHECK (status <> 'SCHEDULED'
        OR (send_at IS NOT NULL AND payload IS NOT NULL))
);

-- 예약 배치가 보낼 시각이 지난 예약을 찾는다(ND-029)
CREATE INDEX ix_notification_schedule_due
    ON notification.notification_schedule (send_at, id)
    WHERE status = 'SCHEDULED';

-- 기한이 지난 "예약"을 건너뜀으로 끝낸다(ND-135, 회차마다 먼저)
CREATE INDEX ix_notification_schedule_expiring
    ON notification.notification_schedule (business_deadline, id)
    WHERE status = 'SCHEDULED';

-- 끝 상태 행 정리(ND-142). "예약" 행은 들지 않는다
CREATE INDEX ix_notification_schedule_finished
    ON notification.notification_schedule (business_deadline, id)
    WHERE status <> 'SCHEDULED';
