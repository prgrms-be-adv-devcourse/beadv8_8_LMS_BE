-- 알림 본 테이블(ND-025, 알림 저장 N2에서 만든다 ND-046). 회원별 최신 20개만 보이고 나머지는 Soft Delete한다(ND-022).
-- 시각: 발행 모듈마다 타입이 달라(LocalDateTime·OffsetDateTime·Instant) 발생·읽은·삭제 시각은 TIMESTAMPTZ로 맞춘다.
-- 생성·수정 시각은 shared BaseEntity(LocalDateTime)다.
CREATE TABLE notification.notification
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 받는 사람(회원 ID). 회원 테이블과 FK·JOIN하지 않는다
    receiver_user_id   BIGINT                         NOT NULL,
    -- 종류 코드(notification-catalog.md)
    kind               VARCHAR(100)                   NOT NULL,
    -- 원본 이벤트 종류와 원본 대상 ID(ND-019·ND-033·ND-045. `<대상 ID>:<회차>`가 있어 문자열)
    source_event_type  VARCHAR(100),
    source_target_id   VARCHAR(255),
    -- 눌렀을 때 이동할 대상
    target_type        VARCHAR(50),
    target_id          VARCHAR(255),
    -- 문구와 값(ND-020). 값에는 형식 버전 v와 언급 회원 닉네임(nicknames)이 있다
    message            TEXT                           NOT NULL,
    payload            JSONB                          NOT NULL,
    -- 하루 묶음 키(ND-032). 묶음 유일 인덱스는 하루 묶음(N8, U9)에서 만든다
    bundle_key         VARCHAR(255),
    -- 문구에 닉네임이 들어간 다른 회원 ID(ND-051). 파기 때 이 회원이 든 알림만 찾는다
    mentioned_user_ids BIGINT[]                       NOT NULL DEFAULT '{}',
    occurred_at        TIMESTAMP(6) WITH TIME ZONE    NOT NULL,
    read_at            TIMESTAMP(6) WITH TIME ZONE,
    deleted_at         TIMESTAMP(6) WITH TIME ZONE,
    created_at         TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at         TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_notification PRIMARY KEY (id)
);

-- 같은 사건은 받는 사람마다 한 번만 만든다. 삭제된 행도 포함해 밀려난 알림이 되살아나지 않는다(ND-019·ND-022)
CREATE UNIQUE INDEX uk_notification_source
    ON notification.notification (source_event_type, source_target_id, receiver_user_id)
    WHERE source_target_id IS NOT NULL;

-- 목록·안 읽은 수·20개 보존 정리(ND-021·ND-022)
CREATE INDEX ix_notification_receiver_alive
    ON notification.notification (receiver_user_id, occurred_at DESC, id DESC)
    WHERE deleted_at IS NULL;

-- 파기된 회원이 언급된 알림 찾기(ND-051)
CREATE INDEX ix_notification_mentioned_users
    ON notification.notification USING GIN (mentioned_user_ids);
