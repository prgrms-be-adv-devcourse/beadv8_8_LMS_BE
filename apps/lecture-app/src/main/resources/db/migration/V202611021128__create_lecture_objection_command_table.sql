-- 강의 내용 다름 이의 제기 명령 이력 (#278, D60 (3)·D71). 고객센터가 보낸 접수(HTTP)·판단·철회(이벤트) 명령을
-- 명령 ID마다 한 번만 처리하고 결과를 남긴다. 같은 명령 ID가 다시 오면 이 행으로 처음 결과를 재현한다.
-- 행을 지우거나 바꾸지 않는다(append-only)
create table lectures.lecture_objection_command
(
    id            BIGINT generated by default as identity not null,
    command_id    VARCHAR(100)                            not null,
    command_type  VARCHAR(20)                             not null,
    inquiry_id    BIGINT                                  not null,
    order_item_id BIGINT                                  not null,
    payload_hash  VARCHAR(64)                             not null,
    outcome       VARCHAR(20)                             not null,
    failure_code  VARCHAR(50),
    processed_at  TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_lecture_objection_command primary key (id),
    -- 같은 명령을 두 번 처리하지 않는다. 동시에 들어온 같은 명령은 이 제약으로 한쪽이 실패하고 다시 받으면 재현된다
    constraint uk_lecture_objection_command_command_id unique (command_id)
);

-- 주문 항목별 명령 이력 조회 (운영 확인)
create index idx_lecture_objection_command_order_item_id on lectures.lecture_objection_command (order_item_id);
