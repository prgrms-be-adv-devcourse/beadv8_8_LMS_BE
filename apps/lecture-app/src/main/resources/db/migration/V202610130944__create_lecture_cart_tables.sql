create table lectures.cart
(
    id         BIGINT generated by default as identity not null,
    user_id    BIGINT                                  not null,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_cart primary key (id),
    constraint uc_cart_user_id unique (user_id)
);

create table lectures.cart_item
(
    id         BIGINT generated by default as identity not null,
    cart_id    BIGINT                                  not null,
    lecture_id BIGINT                                  not null,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_cart_item primary key (id)
);

alter table lectures.cart_item
    add constraint FK_CART_ITEM_ON_CART foreign key (cart_id) references lectures.cart (id);

-- 장바구니에 살아 있는 같은 강의는 하나만 둔다. 뺀 항목(Soft Delete)은 남기고 다시 담을 수 있다 (JPA로 표현할 수 없는 부분 인덱스)
create unique index uk_cart_item_cart_lecture on lectures.cart_item (cart_id, lecture_id) where deleted_at is null;
