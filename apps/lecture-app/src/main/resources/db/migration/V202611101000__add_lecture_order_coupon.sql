-- 주문 항목의 쿠폰 할인 스냅샷과 쿠폰 예약·해제 작업.
-- 할인 합 D = 플랫폼 부담 F + 판매자 부담 S. 구매자 금액은 가격 − D, 판매자 지급액은 가격 − S로 계산하고 저장하지 않는다.
-- 기존 주문은 기본값 0으로 할인 0·기존 금액이 된다(값을 채우는 UPDATE가 필요 없다)
alter table lectures.order_item
    add column discount_hp          BIGINT default 0 not null,
    add column platform_discount_hp BIGINT default 0 not null,
    add column seller_discount_hp   BIGINT default 0 not null,
    add constraint ck_order_item_discount_split
        check (discount_hp = platform_discount_hp + seller_discount_hp),
    add constraint ck_order_item_discount_range
        check (platform_discount_hp >= 0 and seller_discount_hp >= 0 and discount_hp <= price_hp);

-- 주문 항목에 쓴 쿠폰 한 장의 계산 근거. 쿠폰 계산·예약 응답을 그대로 남긴다.
-- member_coupon_id·coupon_id는 쿠폰 모듈의 ID라 FK를 두지 않는다
create table lectures.order_item_coupon
(
    id                  BIGINT generated by default as identity not null,
    order_item_id       BIGINT                                  not null,
    member_coupon_id    BIGINT                                  not null,
    coupon_id           BIGINT                                  not null,
    coupon_type         VARCHAR(20)                             not null,
    apply_order         INTEGER                                 not null,
    base_amount_hp      BIGINT                                  not null,
    discount_hp         BIGINT                                  not null,
    platform_amount_hp  BIGINT                                  not null,
    seller_amount_hp    BIGINT                                  not null,
    -- 계산 때 읽은 generation. 예약 요청에 그대로 보낸다
    expected_generation BIGINT                                  not null,
    -- 예약으로 오른 generation. 예약 결과를 받기 전에는 없다
    reserved_generation BIGINT,
    policy_version      INTEGER                                 not null,
    constraint pk_order_item_coupon primary key (id),
    -- 한 항목에 같은 쿠폰을 두 번 쓰지 않는다
    constraint uk_order_item_coupon_item_member_coupon unique (order_item_id, member_coupon_id),
    -- 한 항목 안의 적용 순서는 겹치지 않는다
    constraint uk_order_item_coupon_item_apply_order unique (order_item_id, apply_order),
    constraint ck_order_item_coupon_discount_split check (discount_hp = platform_amount_hp + seller_amount_hp),
    constraint ck_order_item_coupon_discount_range
        check (platform_amount_hp >= 0 and seller_amount_hp >= 0 and discount_hp <= base_amount_hp)
);

alter table lectures.order_item_coupon
    add constraint fk_order_item_coupon_on_order_item foreign key (order_item_id) references lectures.order_item (id);

-- 주문 하나의 쿠폰 예약(RESERVE)·해제(RELEASE) 요청. 쿠폰 내부 API 호출은 강의 트랜잭션 밖에서 하고,
-- 결과를 모르면 PENDING으로 남아 재시도 배치가 같은 work_id·같은 내용으로 다시 보낸다
create table lectures.order_coupon_work
(
    id              BIGINT generated by default as identity not null,
    order_id        BIGINT                                  not null,
    kind            VARCHAR(20)                             not null,
    -- 쿠폰 모듈의 멱등 키
    work_id         VARCHAR(100)                            not null,
    status          VARCHAR(20)                             not null,
    -- 예약 거절 때 쿠폰이 돌려준 코드
    reject_code     VARCHAR(100),
    attempt_count   INTEGER                                 not null,
    next_attempt_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    version         BIGINT                                  not null,
    constraint pk_order_coupon_work primary key (id),
    constraint uk_order_coupon_work_work_id unique (work_id),
    -- 주문마다 예약 하나, 해제 하나
    constraint uk_order_coupon_work_order_kind unique (order_id, kind)
);

-- 재시도 배치 조회용: 다음 시도 시각이 지난 PENDING 작업
create index idx_order_coupon_work_status_next_attempt_at on lectures.order_coupon_work (status, next_attempt_at);
