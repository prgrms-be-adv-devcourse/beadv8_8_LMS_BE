-- 강의 HP 작업과 시도 이력 (#275, D57). 보류·반환·지급을 지갑 내부 API로 보내기 전에 업무 상태와 함께 기록한다.
-- 두 테이블 모두 행을 지우지 않는다. 시도 행은 결과를 한 번 기록한 뒤 바꾸지 않는다
create table lectures.lecture_hp_task
(
    id                      BIGINT generated by default as identity not null,
    task_type               VARCHAR(255)                            not null,
    purpose                 VARCHAR(255)                            not null,
    request_id              VARCHAR(200)                            not null,
    order_id                BIGINT                                  not null,
    order_item_id           BIGINT                                  not null,
    payer_user_id           BIGINT                                  not null,
    receiver_user_id        BIGINT,
    amount_hp               BIGINT                                  not null,
    payload_fingerprint     VARCHAR(64)                             not null,
    status                  VARCHAR(255)                            not null,
    outcome                 VARCHAR(255),
    attempt_count           INTEGER                                 not null,
    total_attempt_count     INTEGER                                 not null,
    manual_retry_count      INTEGER                                 not null,
    next_attempt_at         TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    claim_token             UUID,
    lease_until             TIMESTAMP(6) WITHOUT TIME ZONE,
    last_error_code         VARCHAR(100),
    last_failed_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    last_retried_by_user_id BIGINT,
    last_retried_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at              TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at              TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    version                 BIGINT                                  not null,
    constraint pk_lecture_hp_task primary key (id),
    -- 요청 ID는 지갑 멱등 키다. 같은 요청 ID로 작업을 두 번 만들지 않는다
    constraint uk_lecture_hp_task_request_id unique (request_id)
);

-- 실행할 작업(대기 중 + 시각 지남, 선점 만료) 조회와 주문·항목별 조회 (D57)
create index idx_lecture_hp_task_status_next_attempt_at on lectures.lecture_hp_task (status, next_attempt_at);
create index idx_lecture_hp_task_status_lease_until on lectures.lecture_hp_task (status, lease_until);
create index idx_lecture_hp_task_order_item_id on lectures.lecture_hp_task (order_item_id);
create index idx_lecture_hp_task_order_id on lectures.lecture_hp_task (order_id);

create table lectures.lecture_hp_task_attempt
(
    id             BIGINT generated by default as identity not null,
    task_id        BIGINT                                  not null,
    attempt_no     INTEGER                                 not null,
    claim_token    UUID                                    not null,
    result         VARCHAR(255),
    error_code     VARCHAR(100),
    raw_error_code VARCHAR(100),
    error_detail   VARCHAR(1000),
    started_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    completed_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_lecture_hp_task_attempt primary key (id),
    constraint uk_lecture_hp_task_attempt_task_attempt_no unique (task_id, attempt_no)
);

alter table lectures.lecture_hp_task_attempt
    add constraint fk_lecture_hp_task_attempt_on_task foreign key (task_id) references lectures.lecture_hp_task (id);
