-- 서비스 간 HP 대사 (#580, D74): 주문 항목 상태와 지갑 보류·지급을 비교한 실행 기록.
-- 고치지 않고 찾아서 남기기만 한다. 정정은 관리자가 HP 작업 재시도·보류 무효화(D73)로 한다.
create table lectures.lecture_hp_reconciliation_run
(
    id             BIGINT generated by default as identity not null,
    -- SCHEDULED(매일 배치)·MANUAL(관리자 실행)
    trigger_type   VARCHAR(20)                             not null,
    triggered_by   BIGINT,
    -- RUNNING·COMPLETED·INCOMPLETE(지갑 조회 실패 등으로 중단, 커서를 옮기지 않음)
    status         VARCHAR(20)                             not null,
    started_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    finished_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    checked_count  INTEGER                                 not null,
    mismatch_count INTEGER                                 not null,
    dead_count     INTEGER                                 not null,
    failure_reason VARCHAR(500),
    version        BIGINT                                  not null,
    constraint pk_lecture_hp_reconciliation_run primary key (id)
);

create index idx_lecture_hp_reconciliation_run_started_at on lectures.lecture_hp_reconciliation_run (started_at);

-- 어긋난 건 (HP 작업 DEAD 표시 포함). 상태는 관리자가 읽는 요약 문자열이다.
-- 지갑에만 있는 보류는 강의에 항목이 없어 주문 ID가 없다
create table lectures.lecture_hp_reconciliation_mismatch
(
    id             BIGINT generated by default as identity not null,
    run_id         BIGINT                                  not null,
    order_item_id  BIGINT                                  not null,
    order_id       BIGINT,
    rule           VARCHAR(50)                             not null,
    item_status    VARCHAR(50),
    lecture_state  VARCHAR(1000)                           not null,
    wallet_state   VARCHAR(1000)                           not null,
    created_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_lecture_hp_reconciliation_mismatch primary key (id),
    constraint fk_lecture_hp_reconciliation_mismatch_run foreign key (run_id)
        references lectures.lecture_hp_reconciliation_run (id)
);

create index idx_lecture_hp_reconciliation_mismatch_run_id on lectures.lecture_hp_reconciliation_mismatch (run_id, id);

-- 지갑 보류 목록(listHolds) 커서. 참조 유형(강의는 LECTURE_ORDER_ITEM)마다 한 행이고, COMPLETED 실행만 앞으로 옮긴다.
-- 지갑의 Instant 값을 KST LocalDateTime으로 바꿔 저장한다 (팀 시각 규칙)
create table lectures.lecture_hp_reconciliation_cursor
(
    reference_type VARCHAR(50)                    not null,
    updated_after  TIMESTAMP(6) WITHOUT TIME ZONE not null,
    after_id       BIGINT                         not null,
    version        BIGINT                         not null,
    constraint pk_lecture_hp_reconciliation_cursor primary key (reference_type)
);

-- 대사 대상: 비교 범위(최근 7일) 안에 바뀐 HP 작업의 주문 항목
create index idx_lecture_hp_task_updated_at on lectures.lecture_hp_task (updated_at);
