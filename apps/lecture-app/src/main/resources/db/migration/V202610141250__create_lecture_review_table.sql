create table lectures.lecture_review
(
    id               BIGINT generated by default as identity not null,
    lecture_id       BIGINT                                  not null,
    order_item_id    BIGINT                                  not null,
    reviewer_user_id BIGINT                                  not null,
    rating           INTEGER                                 not null,
    content          TEXT,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_lecture_review primary key (id),
    constraint ck_lecture_review_rating check (rating between 1 and 5)
);

-- lecture_id·order_item_id는 다른 애그리거트, reviewer_user_id는 다른 모듈의 ID라 FK를 두지 않는다

-- 주문 항목 1건당, 한 회원·한 강의당 살아 있는 리뷰는 하나다. 삭제(Soft Delete) 후에는 다시 쓸 수 있다 (설계 4.7, JPA로 표현할 수 없는 부분 인덱스)
create unique index uk_lecture_review_order_item on lectures.lecture_review (order_item_id) where deleted_at is null;
create unique index uk_lecture_review_lecture_reviewer on lectures.lecture_review (lecture_id, reviewer_user_id)
    where deleted_at is null;

-- 강의별 리뷰 목록(최신순)·평점 집계용
create index idx_lecture_review_lecture_created_at on lectures.lecture_review (lecture_id, created_at)
    where deleted_at is null;
