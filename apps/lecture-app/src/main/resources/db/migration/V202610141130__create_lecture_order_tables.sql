create table lectures.lecture_order
(
    id              BIGINT generated by default as identity not null,
    buyer_user_id   BIGINT                                  not null,
    total_amount_hp BIGINT                                  not null,
    status          VARCHAR(255)                            not null,
    ordered_at      TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    canceled_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_lecture_order primary key (id)
);

create index idx_lecture_order_buyer_user_id on lectures.lecture_order (buyer_user_id);

create table lectures.order_item
(
    id                     BIGINT generated by default as identity not null,
    order_id               BIGINT                                  not null,
    lecture_id             BIGINT                                  not null,
    seller_user_id         BIGINT                                  not null,
    buyer_user_id          BIGINT                                  not null,
    lecture_title_snapshot VARCHAR(255)                            not null,
    price_hp               BIGINT                                  not null,
    status                 VARCHAR(255)                            not null,
    purchased_at           TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    confirmed_at           TIMESTAMP(6) WITHOUT TIME ZONE,
    confirmation_type      VARCHAR(255),
    auto_confirm_at        TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    payout_scheduled_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    paid_out_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    canceled_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    returned_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    objection_status       VARCHAR(255)                            not null,
    objection_reason       TEXT,
    objection_filed_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    objection_resolved_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    version                BIGINT,
    constraint pk_order_item primary key (id)
);

-- lecture_id·seller_user_id·buyer_user_id는 다른 애그리거트·모듈의 ID라 FK를 두지 않는다
alter table lectures.order_item
    add constraint FK_ORDER_ITEM_ON_ORDER foreign key (order_id) references lectures.lecture_order (id);

create index idx_order_item_order_id on lectures.order_item (order_id);

-- 같은 구매자는 같은 강의를 하나만 보유한다. 구매 취소·반환 뒤에는 다시 살 수 있다 (D5, JPA로 표현할 수 없는 부분 인덱스)
create unique index uk_order_item_buyer_lecture_owned on lectures.order_item (buyer_user_id, lecture_id)
    where status in ('PURCHASED', 'CONFIRMED', 'PAID_OUT');

-- 자동 구매 확정·지급 배치 조회용 (설계 7.1)
create index idx_order_item_status_auto_confirm_at on lectures.order_item (status, auto_confirm_at);
create index idx_order_item_status_payout_scheduled_at on lectures.order_item (status, payout_scheduled_at);
