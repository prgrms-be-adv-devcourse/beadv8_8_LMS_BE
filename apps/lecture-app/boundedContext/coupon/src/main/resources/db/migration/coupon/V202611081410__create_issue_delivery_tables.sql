-- 발급 확정 소비의 멱등 기록과 DLT 격리 기록.
-- 기본 스키마가 쿠폰이 아니므로 모든 이름에 coupon. 접두사를 붙인다. 다른 스키마는 참조하지 않는다.

-- 처리한 작업(이벤트)의 멱등 기록. 업무 반영(발급 확정·거절)과 같은 트랜잭션에 넣는다.
-- 발급 요청 이벤트에는 이벤트 ID가 없으므로(팀 Kafka 규칙) 작업 ID는 쿠폰 ID와 발급 요청 ID로 만든 결정적 값이다.
create table coupon.processed_operation
(
    id           BIGINT generated by default as identity not null,
    operation_id VARCHAR(200)                            not null,
    -- 같은 작업 ID의 다른 내용을 가려내는 요청 내용 식별값(회원·epoch·접수 시각·만료 시각)
    content_key  VARCHAR(500)                            not null,
    -- ISSUED·REJECTED
    result       VARCHAR(30)                             not null,
    processed_at TIMESTAMPTZ                             not null,
    constraint pk_processed_operation primary key (id),
    constraint uk_processed_operation_operation_id unique (operation_id)
);

-- 제한 재시도 뒤에도 처리하지 못해 DLT로 보낸 발급 요청 메시지. 관리자가 재발행하거나 영구 거절한다.
-- 역직렬화에 실패한 메시지는 쿠폰 ID·요청 ID를 모르므로 비어 있다. 없는 쿠폰의 메시지도 남겨야 하므로 쿠폰 FK를 두지 않는다.
create table coupon.coupon_dlt_log
(
    id                  BIGINT generated by default as identity not null,
    coupon_id           BIGINT,
    issue_request_id    VARCHAR(100),
    source_topic        VARCHAR(200)                            not null,
    source_partition    INTEGER                                 not null,
    source_offset       BIGINT                                  not null,
    message_key         VARCHAR(200),
    -- 원문. 읽은 메시지는 JSON, 역직렬화에 실패한 메시지는 받은 바이트(UTF-8)
    payload             TEXT                                    not null,
    failure_cause       VARCHAR(1000)                           not null,
    -- PENDING(격리)·REPLAYING(재발행 전송 전 선점)·REPLAYED(원 토픽에 재발행)·REJECTED(영구 거절)
    status              VARCHAR(20)                             not null,
    -- 재발행 선점 시각. REPLAYING이면 반드시 있다. 선점한 프로세스가 죽어도 이 시각부터 lease가 지나면 다시 선점할 수 있다
    replay_claimed_at   TIMESTAMPTZ,
    reject_reason       VARCHAR(500),
    -- 재발행·영구 거절한 관리자
    handled_by          BIGINT,
    handled_at          TIMESTAMPTZ,
    -- 영구 거절 뒤 Redis 수량 보상 결과(RESTORED·ALREADY_COMPENSATED·MARKED_ONLY·NO_RECORD·MEMBER_MISMATCH). 보상 전에는 없다
    compensation_result VARCHAR(30),
    created_at          TIMESTAMPTZ                             not null,
    updated_at          TIMESTAMPTZ                             not null,
    -- 관리자 재발행·영구 거절이 동시에 같은 기록을 바꾸지 않게 하는 낙관적 락
    version             BIGINT                                  not null default 0,
    constraint pk_coupon_dlt_log primary key (id),
    -- 같은 메시지(위치)를 두 번 기록하지 않는다. DLT 전송이 실패해 다시 격리할 때 겹치지 않게 한다
    constraint uk_coupon_dlt_log_source unique (source_topic, source_partition, source_offset),
    constraint ck_coupon_dlt_log_status check (status in ('PENDING', 'REPLAYING', 'REPLAYED', 'REJECTED')),
    constraint ck_coupon_dlt_log_replaying check (status <> 'REPLAYING' or replay_claimed_at is not null),
    constraint ck_coupon_dlt_log_rejected check (status <> 'REJECTED' or reject_reason is not null)
);

-- 같은 발급 요청의 처리 대기 격리는 하나다(재발행 뒤 다시 실패하면 새 기록이 생긴다)
create unique index uk_coupon_dlt_log_pending_request on coupon.coupon_dlt_log (coupon_id, issue_request_id)
    where status = 'PENDING';
create index idx_coupon_dlt_log_status_id on coupon.coupon_dlt_log (status, id);
