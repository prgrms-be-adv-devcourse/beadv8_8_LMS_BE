-- 쿠폰 사용 시도(발급 쿠폰 한 장을 주문 항목 하나에 예약한 기록). 예약 때 만들고 해제·결제·취소로 사실을 더한다.
-- 같은 발급 쿠폰의 재시도는 generation으로 구분한다(예약할 때 오른 generation). 같은 스키마 안의 FK만 둔다.
create table coupon.coupon_usage
(
    id                       BIGINT generated by default as identity not null,
    member_coupon_id         BIGINT                                  not null,
    -- 예약으로 오른 발급 쿠폰 generation
    generation               BIGINT                                  not null,
    coupon_id                BIGINT                                  not null,
    -- SELLER·PLATFORM. 할인 부담 주체
    coupon_type              VARCHAR(20)                             not null,
    -- 예약 때 확인한 쿠폰 정책 버전
    policy_version           INTEGER                                 not null,
    member_id                BIGINT                                  not null,
    -- 강의 모듈의 주문·주문 항목 ID(다른 database라 FK 없음)
    order_id                 BIGINT                                  not null,
    order_item_id            BIGINT                                  not null,
    lecture_id               BIGINT                                  not null,
    -- 항목 원가격 P(HP)
    item_price               BIGINT                                  not null,
    -- 항목 안 적용 순서(1부터. 판매자 쿠폰 → 플랫폼 쿠폰)
    apply_order              INTEGER                                 not null,
    -- 적용 직전 남은 금액(HP)
    base_amount              BIGINT                                  not null,
    -- 이 쿠폰의 할인 d = 플랫폼 부담 f + 판매자 부담 s(HP)
    discount_amount          BIGINT                                  not null,
    platform_amount          BIGINT                                  not null,
    seller_amount            BIGINT                                  not null,
    reservation_work_id      VARCHAR(100)                            not null,
    -- RESERVED·RELEASED. PAID·CANCELED는 결제·취소 연동이 쓴다
    status                   VARCHAR(20)                             not null,
    reserved_at              TIMESTAMPTZ                             not null,
    release_work_id          VARCHAR(100),
    release_reason           VARCHAR(500),
    -- 보상 완료 근거. 지금은 기록만 하고 검증하지 않는다
    release_compensation_ref VARCHAR(200),
    -- 해제 뒤 발급 쿠폰 상태: AVAILABLE(만료 전)·EXPIRED(만료 뒤)
    released_to              VARCHAR(20),
    released_at              TIMESTAMPTZ,
    -- 결제·취소 연동이 쓰는 사실
    paid_event_id            VARCHAR(200),
    paid_at                  TIMESTAMPTZ,
    cancel_event_id          VARCHAR(200),
    cancel_completed_at      TIMESTAMPTZ,
    restored_to              VARCHAR(20),
    restored_at              TIMESTAMPTZ,
    created_at               TIMESTAMPTZ                             not null,
    updated_at               TIMESTAMPTZ                             not null,
    constraint pk_coupon_usage primary key (id),
    -- 발급 쿠폰의 한 사용 시도는 한 행이다
    constraint uk_coupon_usage_member_coupon_generation unique (member_coupon_id, generation),
    constraint fk_coupon_usage_member_coupon foreign key (member_coupon_id) references coupon.member_coupon (id),
    constraint fk_coupon_usage_coupon foreign key (coupon_id) references coupon.coupon (id),
    constraint ck_coupon_usage_coupon_type check (coupon_type in ('SELLER', 'PLATFORM')),
    constraint ck_coupon_usage_status check (status in ('RESERVED', 'RELEASED', 'PAID', 'CANCELED')),
    constraint ck_coupon_usage_generation check (generation >= 1),
    constraint ck_coupon_usage_apply_order check (apply_order >= 1),
    constraint ck_coupon_usage_amounts check (
        item_price >= 0 and base_amount >= 0 and discount_amount >= 0 and platform_amount >= 0 and seller_amount >= 0),
    constraint ck_coupon_usage_discount_split check (discount_amount = platform_amount + seller_amount),
    constraint ck_coupon_usage_discount_range check (discount_amount <= base_amount and base_amount <= item_price),
    -- 판매자 쿠폰은 판매자가, 플랫폼 쿠폰은 플랫폼이 전부 부담한다
    constraint ck_coupon_usage_bearer check (
        (coupon_type = 'SELLER' and platform_amount = 0) or (coupon_type = 'PLATFORM' and seller_amount = 0)),
    constraint ck_coupon_usage_released_to check (released_to is null or released_to in ('AVAILABLE', 'EXPIRED')),
    constraint ck_coupon_usage_restored_to check (restored_to is null or restored_to in ('AVAILABLE', 'EXPIRED')),
    -- 해제한 사용 시도에는 해제 작업·결과·시각이 있다
    constraint ck_coupon_usage_released check (
        status <> 'RELEASED' or (release_work_id is not null and released_to is not null and released_at is not null))
);

-- 발급 쿠폰 한 장은 같은 주문 항목에 동시에 한 번만 예약한다. 해제한 뒤 같은 항목에 다시 예약하면 새 generation의 새 행이다(이력)
create unique index uk_coupon_usage_order_item_member_coupon_reserved
    on coupon.coupon_usage (order_item_id, member_coupon_id) where status = 'RESERVED';

-- 예약 상태 조회는 예약 작업 ID로, 해제 재응답은 주문 ID로 찾는다
create index idx_coupon_usage_reservation_work_id on coupon.coupon_usage (reservation_work_id);
create index idx_coupon_usage_order_id on coupon.coupon_usage (order_id);
