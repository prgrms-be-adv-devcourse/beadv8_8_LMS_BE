-- 쿠폰 기반 테이블: 쿠폰 정책, 발급 쿠폰, 발급 요청 결과, 프로모션 예산 작업.
-- 기본 스키마가 쿠폰이 아니므로 모든 이름에 coupon. 접두사를 붙인다. 같은 스키마 안의 FK만 둔다(다른 스키마는 참조하지 않는다).

-- 쿠폰 정책. 판매자 쿠폰은 DRAFT → REVIEW → OPEN/REJECTED, 플랫폼 쿠폰은 DRAFT → OPEN으로 연다.
create table coupon.coupon
(
    id                    BIGINT generated by default as identity not null,
    -- SELLER(판매자 쿠폰)·PLATFORM(플랫폼 쿠폰). 할인 비용을 누가 부담하는지의 기준
    type                  VARCHAR(20)                             not null,
    -- 신청자 회원 ID. 플랫폼 쿠폰은 발행한 관리자
    applicant_id          BIGINT                                  not null,
    -- LECTURE(특정 강의)·ANY_LECTURE(모든 강의 중 하나)
    target_type           VARCHAR(20)                             not null,
    lecture_id            BIGINT,
    -- 발행 시 강의 가격 snapshot(HP). 특정 강의 대상만 있다
    base_price            BIGINT,
    -- RATE(정률, 퍼센트 정수)·AMOUNT(정액, HP)
    discount_type         VARCHAR(20)                             not null,
    discount_value        BIGINT                                  not null,
    -- 장당 최대 할인액(HP). 모든 강의 대상 정률 쿠폰만 있다
    max_discount_amount   BIGINT,
    quantity              INTEGER                                 not null,
    -- DB에 확정된 발급 수
    issued_count          INTEGER                                 not null default 0,
    issue_start_at        TIMESTAMPTZ                             not null,
    issue_end_at          TIMESTAMPTZ                             not null,
    -- RELATIVE(최초 접수 시각 + expiry_days일)·FIXED(expires_at)
    expiry_type           VARCHAR(20)                             not null,
    expiry_days           INTEGER,
    expires_at            TIMESTAMPTZ,
    stackable             BOOLEAN                                 not null,
    policy_version        INTEGER                                 not null default 1,
    -- DRAFT·REVIEW·REJECTED·OPEN·SUSPENDED·CLOSED
    status                VARCHAR(20)                             not null,
    reject_reason         VARCHAR(500),
    -- 프로모션 예산 예약 ID. 플랫폼 쿠폰이 예산을 확보한 뒤에 있다
    budget_reservation_id VARCHAR(100),
    epoch                 BIGINT                                  not null default 1,
    -- Redis 발급 저장소(issue-control·stock·epoch) 준비 여부
    redis_ready           BOOLEAN                                 not null default false,
    created_by            BIGINT                                  not null,
    created_at            TIMESTAMPTZ                             not null,
    updated_at            TIMESTAMPTZ                             not null,
    version               BIGINT                                  not null default 0,
    constraint pk_coupon primary key (id),
    constraint ck_coupon_type check (type in ('SELLER', 'PLATFORM')),
    constraint ck_coupon_target_type check (target_type in ('LECTURE', 'ANY_LECTURE')),
    constraint ck_coupon_discount_type check (discount_type in ('RATE', 'AMOUNT')),
    constraint ck_coupon_expiry_type check (expiry_type in ('RELATIVE', 'FIXED')),
    constraint ck_coupon_status check (status in ('DRAFT', 'REVIEW', 'REJECTED', 'OPEN', 'SUSPENDED', 'CLOSED')),
    constraint ck_coupon_quantity check (quantity >= 1),
    constraint ck_coupon_issued_count check (issued_count >= 0 and issued_count <= quantity),
    constraint ck_coupon_issue_period check (issue_start_at < issue_end_at),
    -- 판매자 쿠폰은 본인 특정 강의에만 적용한다
    constraint ck_coupon_seller_target check (type = 'PLATFORM' or target_type = 'LECTURE'),
    constraint ck_coupon_lecture_target check (
        (target_type = 'LECTURE' and lecture_id is not null and base_price is not null and base_price >= 0)
            or (target_type = 'ANY_LECTURE' and lecture_id is null and base_price is null)),
    constraint ck_coupon_discount_value check (
        (discount_type = 'RATE' and discount_value between 1 and 100)
            or (discount_type = 'AMOUNT' and discount_value >= 1)),
    constraint ck_coupon_max_discount check (
        (target_type = 'ANY_LECTURE' and discount_type = 'RATE' and max_discount_amount is not null and max_discount_amount >= 1)
            or (not (target_type = 'ANY_LECTURE' and discount_type = 'RATE') and max_discount_amount is null)),
    constraint ck_coupon_expiry check (
        (expiry_type = 'RELATIVE' and expiry_days is not null and expiry_days >= 1 and expires_at is null)
            or (expiry_type = 'FIXED' and expires_at is not null and expiry_days is null))
);

-- 발급 쿠폰(회원이 받은 한 장). 행은 발급 확정 소비자가 넣는다.
create table coupon.member_coupon
(
    id                    BIGINT generated by default as identity not null,
    member_id             BIGINT                                  not null,
    coupon_id             BIGINT                                  not null,
    issue_request_id      VARCHAR(100)                            not null,
    -- AVAILABLE·RESERVED·USED·EXPIRED
    status                VARCHAR(20)                             not null,
    -- 사용 시도 세대. 새 사용 시도에서만 오른다
    generation            BIGINT                                  not null default 0,
    current_order_item_id BIGINT,
    issued_at             TIMESTAMPTZ                             not null,
    expires_at            TIMESTAMPTZ                             not null,
    reserved_at           TIMESTAMPTZ,
    used_at               TIMESTAMPTZ,
    created_at            TIMESTAMPTZ                             not null,
    updated_at            TIMESTAMPTZ                             not null,
    constraint pk_member_coupon primary key (id),
    -- 회원당 같은 쿠폰 1장, 같은 발급 요청은 한 장. 발급 요청 ID는 쿠폰 안에서만 유일하다
    constraint uk_member_coupon_member_coupon unique (member_id, coupon_id),
    constraint uk_member_coupon_issue_request unique (coupon_id, issue_request_id),
    constraint fk_member_coupon_coupon foreign key (coupon_id) references coupon.coupon (id),
    constraint ck_member_coupon_status check (status in ('AVAILABLE', 'RESERVED', 'USED', 'EXPIRED')),
    constraint ck_member_coupon_generation check (generation >= 0)
);

create index idx_member_coupon_member_status on coupon.member_coupon (member_id, status);
create index idx_member_coupon_coupon on coupon.member_coupon (coupon_id);
create index idx_member_coupon_status_expires_at on coupon.member_coupon (status, expires_at);

-- 발급 요청의 최종 결과. 발급 확정 소비자가 쓰고, 요청 상태 조회가 읽는다. 발급 요청 ID는 쿠폰 안에서만 유일하다.
create table coupon.coupon_issue_request
(
    id                  BIGINT generated by default as identity not null,
    coupon_id           BIGINT       not null,
    issue_request_id    VARCHAR(100) not null,
    member_id           BIGINT       not null,
    epoch               BIGINT       not null,
    -- ISSUED·REJECTED
    result              VARCHAR(20)  not null,
    reject_reason       VARCHAR(500),
    -- 최초 접수 시각(Redis 접수 때 정한 값)
    accepted_at         TIMESTAMPTZ  not null,
    processed_at        TIMESTAMPTZ  not null,
    member_coupon_id    BIGINT,
    -- 거절 뒤 Redis 수량 보상 진행 상태. 값 목록은 보상 구현 때 정한다
    compensation_status VARCHAR(30),
    constraint pk_coupon_issue_request primary key (id),
    constraint uk_coupon_issue_request_coupon_request unique (coupon_id, issue_request_id),
    constraint fk_coupon_issue_request_coupon foreign key (coupon_id) references coupon.coupon (id),
    constraint ck_coupon_issue_request_result check (result in ('ISSUED', 'REJECTED')),
    constraint ck_coupon_issue_request_member_coupon check (
        (result = 'ISSUED' and member_coupon_id is not null) or (result = 'REJECTED' and member_coupon_id is null))
);

-- 프로모션 예산 예약·해제 작업. 쿠폰 상태 변경과 같은 트랜잭션에 저장하고, billing 호출은 트랜잭션 밖에서 한다.
create table coupon.budget_work
(
    work_id    VARCHAR(100) not null,
    coupon_id  BIGINT       not null,
    -- RESERVE·RELEASE
    kind       VARCHAR(20)  not null,
    amount     BIGINT       not null,
    reason     VARCHAR(500),
    -- PENDING·DONE·FAILED
    status     VARCHAR(20)  not null,
    -- DONE이면 예약 ID, FAILED면 실패 사유
    result     VARCHAR(500),
    created_at TIMESTAMPTZ  not null,
    updated_at TIMESTAMPTZ  not null,
    constraint pk_budget_work primary key (work_id),
    constraint fk_budget_work_coupon foreign key (coupon_id) references coupon.coupon (id),
    constraint ck_budget_work_kind check (kind in ('RESERVE', 'RELEASE')),
    constraint ck_budget_work_status check (status in ('PENDING', 'DONE', 'FAILED')),
    constraint ck_budget_work_amount check (amount >= 0)
);

create index idx_budget_work_coupon_kind on coupon.budget_work (coupon_id, kind);
