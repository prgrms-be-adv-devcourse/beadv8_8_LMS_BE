-- 쿠폰 Redis 유실 복구 실행. 단계는 BLOCKED → BOUNDARY_FIXED → RESULTS_CHECKED → REBUILDING → REBUILT → RESUMING → RESUMED 순서로만
-- 나아간다. REBUILDING·RESUMING은 Redis 재구축·활성화 전에 커밋하는 선점이다(같은 복구의 재구축·재개가 동시에 Redis를 바꾸지 않게).
-- 재구축 선점(REBUILDING) 전에는 관리자가 취소할 수 있다(ABORTED, 접수 차단은 유지). 예외로 재개 결과를 모르는 RESUMING에서 Redis 유실이
-- 확인되면 취소할 수 있고, 그 사유를 abort_reason에 남긴다.
-- 쿠폰마다 끝나지 않은(RESUMED·ABORTED가 아닌) 복구는 하나뿐이다(부분 유일 인덱스). 쿠폰은 ID로만 참조한다.
create table coupon.recovery_run
(
    id                BIGINT generated by default as identity not null,
    coupon_id         BIGINT                                  not null,
    -- 복구 전 epoch. 재개 전까지 쿠폰 epoch는 이 값이다
    previous_epoch    BIGINT                                  not null,
    -- 재개 때 활성화할 epoch(previous_epoch + 1)
    new_epoch         BIGINT                                  not null,
    step              VARCHAR(20)                             not null,
    -- Redis 접수 기록을 믿을 수 없다(유실 의심). 그 사이 접수는 결과를 증명할 수 없어 UNKNOWN으로 남을 수 있다
    requests_lost     BOOLEAN                                 not null default false,
    -- requests 재발행을 마친 시각과 건수
    republished_at    TIMESTAMPTZ,
    republished_count INTEGER,
    -- 재발행 뒤 발급 요청 토픽·DLT 토픽의 partition별 끝 offset("partition:offset,...")
    kafka_boundary    VARCHAR(1000),
    dlt_boundary      VARCHAR(1000),
    -- 마지막 결과 확인의 미처리 합계와 내역(재발행 대기·Kafka lag·DLT PENDING)
    unresolved_count  BIGINT,
    unresolved_detail VARCHAR(500),
    -- 관리자가 적은 재개 근거와 재개 때 확인한 수량 대사 결과
    resume_basis      VARCHAR(1000),
    resume_evidence   VARCHAR(500),
    started_by        BIGINT                                  not null,
    created_at        TIMESTAMPTZ                             not null,
    updated_at        TIMESTAMPTZ                             not null,
    resumed_at        TIMESTAMPTZ,
    -- 복구를 취소한 관리자와 시각. 취소한 복구(ABORTED)에만 있다
    aborted_by        BIGINT,
    aborted_at        TIMESTAMPTZ,
    -- 예외 취소(재개 결과를 모르는 채 Redis 유실 확인)의 사유. 재구축 전 취소이거나 취소하지 않았으면 null
    abort_reason      VARCHAR(100),
    -- 신규 접수·재발행 배치가 멈춘 시각(Redis 차단을 마친 시각). 경계 확정은 여기서 생산자 전송 수명이 지난 뒤에만 한다
    blocked_at        TIMESTAMPTZ,
    -- 진행 중인 재구축·재개 선점의 시각(선점 토큰). 선점이 없으면 null
    claimed_at        TIMESTAMPTZ,
    version           BIGINT                                  not null default 0,
    constraint pk_recovery_run primary key (id),
    constraint ck_recovery_run_step check (step in ('BLOCKED', 'BOUNDARY_FIXED', 'RESULTS_CHECKED', 'REBUILDING', 'REBUILT', 'RESUMING', 'RESUMED', 'ABORTED')),
    constraint ck_recovery_run_epoch check (new_epoch = previous_epoch + 1),
    constraint ck_recovery_run_aborted check ((step = 'ABORTED') = (aborted_by is not null and aborted_at is not null)),
    constraint ck_recovery_run_republished_count check (republished_count is null or republished_count >= 0),
    constraint ck_recovery_run_unresolved_count check (unresolved_count is null or unresolved_count >= 0)
);

-- 쿠폰마다 끝나지 않은 복구는 하나. 동시에 두 복구를 시작하면 늦은 쪽이 이 인덱스에 걸린다. 취소한 복구는 새 복구를 막지 않는다
create unique index uk_recovery_run_active on coupon.recovery_run (coupon_id) where step not in ('RESUMED', 'ABORTED');

create index ix_recovery_run_coupon on coupon.recovery_run (coupon_id, id);
