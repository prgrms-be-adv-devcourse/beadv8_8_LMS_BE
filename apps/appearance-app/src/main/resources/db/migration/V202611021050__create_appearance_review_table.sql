-- 출연 리뷰 (#512): 출연 확인(CONFIRMED)이 끝난 출연에서 호스트·게스트가 서로에게 남긴 리뷰·별점. 출연당 방향별 1건(최대 2건).
-- 수정·삭제는 없다. 블라인드 공개라 상대 리뷰가 들어온 트랜잭션에서 두 리뷰의 published_at을 함께 채운다(그 전에는 null).
-- reviewer_id·reviewee_id는 회원 ID 그대로다 (회원 테이블에 FK를 걸지 않는다).
create table appearances.reviews
(
    id            BIGINT generated by default as identity not null,
    appearance_id BIGINT                                  not null,
    reviewer_id   BIGINT                                  not null,
    reviewee_id   BIGINT                                  not null,
    -- 리뷰 받은 사람이 그 출연에서 맡은 역할 (HOST·GUEST)
    reviewee_role VARCHAR(255)                            not null,
    rating        INTEGER                                 not null,
    content       VARCHAR(1000),
    published_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    version       BIGINT                                  not null,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearance_reviews primary key (id),
    constraint fk_appearance_reviews_appearance foreign key (appearance_id) references appearances.appearances (id),
    -- 출연 하나에 작성자 1명당 한 번만 쓴다. 같은 사람이 동시에 써도 DB에서 막는다
    constraint uk_appearance_reviews_appearance_reviewer unique (appearance_id, reviewer_id),
    constraint ck_appearance_reviews_rating check (rating between 1 and 5),
    constraint ck_appearance_reviews_reviewer_reviewee check (reviewer_id <> reviewee_id)
);

-- 회원이 받은 리뷰 조회 (공개된 것만, 공개 시각순)
create index idx_appearance_reviews_reviewee_id_published_at on appearances.reviews (reviewee_id, published_at);
