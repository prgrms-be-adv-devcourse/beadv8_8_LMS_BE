-- 서비스 간 HP 대사 (#581): 요청서·모집글·출연 상태와 지갑 보류·지급을 비교한 실행 기록.
-- 고치지 않고 찾아서 남기기만 한다. 정정은 관리자가 HP 작업 재시도·보류 무효화로 한다.
create table appearances.hp_reconciliation_runs
(
    id             BIGINT generated by default as identity not null,
    -- SCHEDULED(매일 배치)·MANUAL(관리자 실행)
    trigger_type   VARCHAR(255)                            not null,
    triggered_by   BIGINT,
    -- RUNNING·COMPLETED·INCOMPLETE(지갑 조회 실패로 중단, 커서를 옮기지 않음)
    status         VARCHAR(255)                            not null,
    started_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    finished_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    checked_count  INTEGER                                 not null,
    mismatch_count INTEGER                                 not null,
    dead_count     INTEGER                                 not null,
    failure_reason VARCHAR(500),
    version        BIGINT                                  not null,
    created_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_hp_reconciliation_runs primary key (id)
);

create index idx_hp_reconciliation_runs_started_at on appearances.hp_reconciliation_runs (started_at);

-- 어긋난 건 (HP 작업 DEAD 표시 포함). 상태는 사람이 읽는 요약 문자열이다
create table appearances.hp_reconciliation_mismatches
(
    id               BIGINT generated by default as identity not null,
    run_id           BIGINT                                  not null,
    -- APPEARANCE_REQUEST·APPEARANCE_RECRUIT (지갑 참조 유형)
    reference_type   VARCHAR(255)                            not null,
    reference_id     BIGINT                                  not null,
    appearance_id    BIGINT,
    rule             VARCHAR(255)                            not null,
    appearance_state VARCHAR(1000)                           not null,
    wallet_state     VARCHAR(1000)                           not null,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_hp_reconciliation_mismatches primary key (id),
    constraint fk_hp_reconciliation_mismatches_run foreign key (run_id) references appearances.hp_reconciliation_runs (id)
);

create index idx_hp_reconciliation_mismatches_run_id on appearances.hp_reconciliation_mismatches (run_id, id);

-- 지갑 보류 목록(listHolds) 커서. 참조 유형마다 한 행이고, COMPLETED 실행만 앞으로 옮긴다.
-- 지갑의 Instant 값을 KST LocalDateTime으로 바꿔 저장한다 (팀 시각 규칙)
create table appearances.hp_reconciliation_cursors
(
    reference_type VARCHAR(255)                   not null,
    updated_after  TIMESTAMP(6) WITHOUT TIME ZONE not null,
    after_id       BIGINT                         not null,
    version        BIGINT                         not null,
    created_at     TIMESTAMP(6) WITHOUT TIME ZONE not null,
    updated_at     TIMESTAMP(6) WITHOUT TIME ZONE not null,
    constraint pk_hp_reconciliation_cursors primary key (reference_type)
);
