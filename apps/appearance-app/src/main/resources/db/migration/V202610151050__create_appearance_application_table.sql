-- 출연 모집 지원: 게스트 한 명이 모집글 하나에 낸 지원.
-- recruit_id는 같은 모듈의 모집글, guest_id는 회원 ID 그대로다 (회원 테이블에 FK를 걸지 않는다).
create table appearances.applications
(
    id           BIGINT generated by default as identity not null,
    recruit_id   BIGINT                                  not null,
    guest_id     BIGINT                                  not null,
    message      VARCHAR(500),
    status       VARCHAR(255)                            not null,
    -- 아래 두 컬럼은 호스트 응답·게스트 취소에서 채운다
    responded_at TIMESTAMP(6) WITHOUT TIME ZONE,
    withdrawn_at TIMESTAMP(6) WITHOUT TIME ZONE,
    version      BIGINT                                  not null,
    created_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearance_applications primary key (id),
    constraint fk_appearance_applications_recruit foreign key (recruit_id) references appearances.recruits (id),
    -- 한 모집글에는 게스트 1명당 한 번만 지원한다 (취소·거절 후 재지원 불가). 동시 지원도 DB에서 막는다
    constraint uk_appearance_applications_recruit_guest unique (recruit_id, guest_id)
);

-- 모집글의 지원자 목록(호스트, 최신순). 지원자 수 집계도 recruit_id로 찾는다
create index idx_appearance_applications_recruit_id_created_at on appearances.applications (recruit_id, created_at);
-- 내 지원 목록(게스트, 최신순)
create index idx_appearance_applications_guest_id_created_at on appearances.applications (guest_id, created_at);
