-- 출연: 출연 성립으로 생긴 거래 1건 (게스트 1명 기준). 성립 후 확인·취소·지급은 이 단위로 처리한다.
-- 출연료·방송 예정 일시는 성립 시점 값을 그대로 둔다(스냅샷). 출처(요청서·모집)와 관계없이 이 값으로 계산한다.
create table appearances.appearances
(
    id             BIGINT generated by default as identity not null,
    source_type    VARCHAR(255)                            not null,
    request_id     BIGINT,
    application_id BIGINT,
    recruit_id     BIGINT,
    host_id        BIGINT                                  not null,
    guest_id       BIGINT                                  not null,
    fee            BIGINT                                  not null,
    scheduled_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    status         VARCHAR(255)                            not null,
    established_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    -- 아래는 출연 확인·취소 처리에서 채운다
    confirm_type   VARCHAR(255),
    penalty_amount BIGINT,
    confirmed_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    no_show_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    disputed_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    canceled_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    version        BIGINT                                  not null,
    created_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearances primary key (id),
    -- 요청서·지원 하나에서 출연은 하나만 생긴다
    constraint uk_appearances_request_id unique (request_id),
    constraint uk_appearances_application_id unique (application_id),
    constraint ck_appearances_source check (
        (source_type = 'REQUEST' and request_id is not null and application_id is null)
            or (source_type = 'RECRUIT' and application_id is not null and request_id is null)),
    constraint ck_appearances_fee check (fee > 0)
);

create index idx_appearances_host_id on appearances.appearances (host_id);
create index idx_appearances_guest_id on appearances.appearances (guest_id);

-- HP 작업: 출연 모듈이 Billing에 요청해야 하는 HP 이동(반환·지급 등) 한 건.
-- 업무 상태 변경과 같은 트랜잭션에 기록하고, 커밋 후 실행한다. 실패하면 남아서 다시 실행되고, 계속 실패하면 DEAD로 격리한다.
create table appearances.hp_tasks
(
    id              BIGINT generated by default as identity not null,
    task_type       VARCHAR(255)                            not null,
    ref_type        VARCHAR(255)                            not null,
    ref_id          BIGINT                                  not null,
    appearance_id   BIGINT,
    member_id       BIGINT                                  not null,
    amount          BIGINT                                  not null,
    reason          VARCHAR(255)                            not null,
    idempotency_key VARCHAR(255)                            not null,
    status          VARCHAR(255)                            not null,
    attempt_count   INTEGER                                 not null,
    next_attempt_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    last_error      VARCHAR(1000),
    completed_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    version         BIGINT                                  not null,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_hp_tasks primary key (id),
    -- 같은 HP 이동을 두 번 기록하지 않는다 (Billing 멱등 키와 같은 값)
    constraint uk_hp_tasks_idempotency_key unique (idempotency_key),
    constraint ck_hp_tasks_amount check (amount > 0),
    constraint ck_hp_tasks_attempt_count check (attempt_count >= 0)
);

-- 재시도 대상 찾기 (상태, 다음 시도 시각)
create index idx_hp_tasks_status_next_attempt_at on appearances.hp_tasks (status, next_attempt_at);
-- 대상(요청서·모집글)별 작업 조회
create index idx_hp_tasks_ref on appearances.hp_tasks (ref_type, ref_id);
