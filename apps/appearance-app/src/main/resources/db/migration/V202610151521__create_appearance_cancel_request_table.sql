-- 출연 취소 요청 (#231): 출연이 성립한 뒤 게스트가 보낸 취소 요청. 출연 1건당 최대 2건(거절 뒤 1회 재요청)이라 이력을 행으로 남긴다.
create table appearances.cancel_requests
(
    id            BIGINT generated by default as identity not null,
    appearance_id BIGINT                                  not null,
    host_id       BIGINT                                  not null,
    guest_id      BIGINT                                  not null,
    sequence      INTEGER                                 not null,
    reason        VARCHAR(500)                            not null,
    status        VARCHAR(255)                            not null,
    reject_reason VARCHAR(500),
    responded_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    version       BIGINT                                  not null,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearance_cancel_requests primary key (id),
    constraint fk_appearance_cancel_requests_appearance foreign key (appearance_id) references appearances.appearances (id),
    -- 출연 하나에서 순번(1, 2…)은 겹치지 않는다 (상세 이력은 이 인덱스로 순번 순 조회)
    constraint uk_appearance_cancel_requests_appearance_sequence unique (appearance_id, sequence),
    constraint ck_appearance_cancel_requests_sequence check (sequence > 0)
);

-- 처리 중인 취소 요청은 출연당 하나만 (동시 요청을 DB에서도 막는다). 자동 거절 배치도 이 인덱스로 처리 중인 요청을 찾는다
create unique index uk_appearance_cancel_requests_pending on appearances.cancel_requests (appearance_id)
    where status = 'REQUESTED';

-- 내 출연 목록(호스트·게스트, 최신순): 기존 단일 컬럼 인덱스를 정렬까지 포함한 인덱스로 바꾼다
drop index appearances.idx_appearances_host_id;
drop index appearances.idx_appearances_guest_id;
create index idx_appearances_host_id_created_at on appearances.appearances (host_id, created_at);
create index idx_appearances_guest_id_created_at on appearances.appearances (guest_id, created_at);
