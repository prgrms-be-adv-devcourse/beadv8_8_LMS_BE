CREATE SCHEMA IF NOT EXISTS customersupport;

-- 회원의 1:1 문의. user_id는 회원 ID만 담는다(회원 테이블에 FK를 걸지 않는다).
create table customersupport.inquiry
(
    id         BIGINT generated by default as identity not null,
    user_id    BIGINT                                  not null,
    category   VARCHAR(255)                            not null,
    title      VARCHAR(100)                            not null,
    content    TEXT                                    not null,
    status     VARCHAR(255)                            not null,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_inquiry primary key (id)
);

-- 내 문의 목록 조회(user_id, 최신순)
create index idx_inquiry_user_id on customersupport.inquiry (user_id);
