-- 문의에 대한 관리자 답변. 문의 1건에 답변 여러 개. admin_user_id는 회원 ID만 담는다(회원 테이블에 FK를 걸지 않는다).
create table customersupport.inquiry_reply
(
    id            BIGINT generated by default as identity not null,
    inquiry_id    BIGINT                                  not null,
    admin_user_id BIGINT                                  not null,
    content       TEXT                                    not null,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_inquiry_reply primary key (id),
    constraint fk_inquiry_reply_on_inquiry foreign key (inquiry_id) references customersupport.inquiry (id)
);

-- 문의 상세의 답변 목록
create index idx_inquiry_reply_inquiry_id on customersupport.inquiry_reply (inquiry_id);
