CREATE SCHEMA IF NOT EXISTS lectures;

create table lectures.lecture
(
    id                      BIGINT generated by default as identity not null,
    seller_user_id          BIGINT                                  not null,
    thumbnail_file_id       BIGINT,
    title                   VARCHAR(255)                            not null,
    description             TEXT,
    price_hp                BIGINT                                  not null,
    status                  VARCHAR(255)                            not null,
    rejection_reason        TEXT,
    inspection_requested_at TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    inspected_at            TIMESTAMP(6) WITHOUT TIME ZONE,
    inspected_by            BIGINT,
    version                 BIGINT,
    created_at              TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at              TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at              TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_lecture primary key (id)
);

create table lectures.lecture_content
(
    id           BIGINT generated by default as identity not null,
    lecture_id   BIGINT                                  not null,
    file_id      BIGINT                                  not null,
    title        VARCHAR(255)                            not null,
    sequence     INTEGER                                 not null,
    content_type VARCHAR(255)                            not null,
    created_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at   TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    deleted_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_lecture_content primary key (id)
);

alter table lectures.lecture_content
    add constraint FK_LECTURE_CONTENT_ON_LECTURE foreign key (lecture_id) references lectures.lecture (id);

create index idx_lecture_content_lecture_id on lectures.lecture_content (lecture_id);