CREATE SCHEMA IF NOT EXISTS billing;

CREATE TABLE billing.wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT NOT NULL,
    charge_balance_hp BIGINT NOT NULL DEFAULT 0,
    revenue_balance_hp BIGINT NOT NULL DEFAULT 0,
    held_charge_hp BIGINT NOT NULL DEFAULT 0,
    held_revenue_hp BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_wallet PRIMARY KEY (id),
    CONSTRAINT uk_wallet_user_id UNIQUE (user_id),
    CONSTRAINT ck_wallet_1 CHECK (charge_balance_hp >= 0),
    CONSTRAINT ck_wallet_2 CHECK (revenue_balance_hp >= 0),
    CONSTRAINT ck_wallet_3 CHECK (held_charge_hp >= 0),
    CONSTRAINT ck_wallet_4 CHECK (held_revenue_hp >= 0)
);

CREATE TABLE billing.point_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wallet_id BIGINT NOT NULL,
    point_type VARCHAR(255) NOT NULL,
    balance_bucket VARCHAR(255) NOT NULL,
    amount_hp BIGINT NOT NULL,
    transaction_type VARCHAR(255) NOT NULL,
    reference_type VARCHAR(255) NOT NULL,
    reference_id BIGINT NOT NULL,
    operation_key VARCHAR(255) NOT NULL,
    original_ledger_id BIGINT,
    idempotency_key VARCHAR(255) NOT NULL,
    description TEXT,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_ledger PRIMARY KEY (id),
    CONSTRAINT uk_point_ledger_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_point_ledger_1 CHECK (amount_hp <> 0),
    CONSTRAINT ck_point_ledger_point_type CHECK (point_type IN ('CHARGE', 'REVENUE')),
    CONSTRAINT ck_point_ledger_balance_bucket CHECK (balance_bucket IN ('AVAILABLE', 'HELD')),
    CONSTRAINT ck_point_ledger_transaction_type CHECK (transaction_type IN ('CHARGE', 'HOLD', 'RELEASE', 'PAYOUT', 'REFUND', 'EXCHANGE', 'REVERSAL')),
    CONSTRAINT ck_point_ledger_reference_type CHECK (reference_type IN ('LECTURE_ORDER', 'LECTURE_ORDER_ITEM', 'APPEARANCE_REQUEST', 'APPEARANCE_RECRUIT', 'RECRUIT_APPEARANCE', 'POINT_CHARGE', 'POINT_REFUND_REQUEST', 'EXCHANGE', 'SETTLEMENT'))
);

CREATE TABLE billing.point_hold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wallet_id BIGINT NOT NULL,
    reference_type VARCHAR(255) NOT NULL,
    reference_id BIGINT NOT NULL,
    original_charge_hp BIGINT NOT NULL,
    original_revenue_hp BIGINT NOT NULL,
    held_charge_hp BIGINT NOT NULL,
    held_revenue_hp BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    held_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_hold PRIMARY KEY (id),
    CONSTRAINT uk_point_hold_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_point_hold_1 CHECK (original_charge_hp >= 0),
    CONSTRAINT ck_point_hold_2 CHECK (original_revenue_hp >= 0),
    CONSTRAINT ck_point_hold_3 CHECK (held_charge_hp >= 0 AND held_charge_hp <= original_charge_hp),
    CONSTRAINT ck_point_hold_4 CHECK (held_revenue_hp >= 0 AND held_revenue_hp <= original_revenue_hp),
    CONSTRAINT ck_point_hold_reference_type CHECK (reference_type IN ('LECTURE_ORDER', 'LECTURE_ORDER_ITEM', 'APPEARANCE_REQUEST', 'APPEARANCE_RECRUIT', 'RECRUIT_APPEARANCE', 'POINT_CHARGE', 'POINT_REFUND_REQUEST', 'EXCHANGE', 'SETTLEMENT')),
    CONSTRAINT ck_point_hold_status CHECK (status IN ('HELD', 'PARTIALLY_PROCESSED', 'RELEASED', 'PAID', 'MIXED'))
);

CREATE TABLE billing.point_hold_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    point_hold_id BIGINT NOT NULL,
    reference_type VARCHAR(255) NOT NULL,
    reference_id BIGINT NOT NULL,
    action_type VARCHAR(255) NOT NULL,
    charge_amount_hp BIGINT NOT NULL,
    revenue_amount_hp BIGINT NOT NULL,
    idempotency_key VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_hold_detail PRIMARY KEY (id),
    CONSTRAINT uk_point_hold_detail_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_point_hold_detail_1 CHECK (charge_amount_hp >= 0),
    CONSTRAINT ck_point_hold_detail_2 CHECK (revenue_amount_hp >= 0),
    CONSTRAINT ck_point_hold_detail_3 CHECK (charge_amount_hp > 0 OR revenue_amount_hp > 0),
    CONSTRAINT ck_point_hold_detail_reference_type CHECK (reference_type IN ('LECTURE_ORDER', 'LECTURE_ORDER_ITEM', 'APPEARANCE_REQUEST', 'APPEARANCE_RECRUIT', 'RECRUIT_APPEARANCE', 'POINT_CHARGE', 'POINT_REFUND_REQUEST', 'EXCHANGE', 'SETTLEMENT')),
    CONSTRAINT ck_point_hold_detail_action_type CHECK (action_type IN ('RELEASE', 'PAYOUT'))
);

CREATE TABLE billing.point_charge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    wallet_id BIGINT NOT NULL,
    amount_hp BIGINT NOT NULL,
    payment_amount_krw BIGINT NOT NULL,
    remaining_principal_hp BIGINT NOT NULL,
    pg_provider VARCHAR(255) NOT NULL,
    pg_order_id VARCHAR(255) NOT NULL,
    pg_payment_key VARCHAR(255),
    status VARCHAR(255) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_charge PRIMARY KEY (id),
    CONSTRAINT uk_point_charge_pg_order_id UNIQUE (pg_order_id),
    CONSTRAINT uk_point_charge_pg_payment_key UNIQUE (pg_payment_key),
    CONSTRAINT ck_point_charge_1 CHECK (amount_hp >= 1000 AND amount_hp % 1000 = 0),
    CONSTRAINT ck_point_charge_2 CHECK (payment_amount_krw > 0),
    CONSTRAINT ck_point_charge_3 CHECK (remaining_principal_hp >= 0 AND remaining_principal_hp <= amount_hp),
    CONSTRAINT ck_point_charge_pg_provider CHECK (pg_provider IN ('TOSS_PAYMENTS')),
    CONSTRAINT ck_point_charge_status CHECK (status IN ('PENDING', 'COMPLETED', 'PARTIALLY_REFUNDED', 'REFUNDED', 'FAILED'))
);

CREATE TABLE billing.point_charge_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    charge_id BIGINT NOT NULL,
    point_hold_id BIGINT NOT NULL,
    amount_hp BIGINT NOT NULL,
    remaining_held_hp BIGINT NOT NULL,
    consumed_hp BIGINT NOT NULL,
    released_hp BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_charge_usage PRIMARY KEY (id),
    CONSTRAINT uk_point_charge_usage_charge_id_point_hold_id UNIQUE (charge_id, point_hold_id),
    CONSTRAINT ck_point_charge_usage_1 CHECK (amount_hp > 0),
    CONSTRAINT ck_point_charge_usage_2 CHECK (remaining_held_hp >= 0),
    CONSTRAINT ck_point_charge_usage_3 CHECK (consumed_hp >= 0),
    CONSTRAINT ck_point_charge_usage_4 CHECK (released_hp >= 0),
    CONSTRAINT ck_point_charge_usage_5 CHECK (remaining_held_hp::numeric + consumed_hp + released_hp = amount_hp::numeric),
    CONSTRAINT ck_point_charge_usage_status CHECK (status IN ('HELD', 'PARTIALLY_PROCESSED', 'CONSUMED', 'RELEASED', 'MIXED'))
);

