-- JPA를 우회하는 UPDATE/DELETE도 차단한다. 정정은 역분개 INSERT로 기록한다.
CREATE FUNCTION billing.reject_point_ledger_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'POINT_LEDGER is append-only; record a reversal instead'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_point_ledger_append_only
BEFORE UPDATE OR DELETE ON billing.point_ledger
FOR EACH ROW EXECUTE FUNCTION billing.reject_point_ledger_mutation();

