package com.hapbang.billing.domain;

// 수익 HP 환전 요청의 진행 상태를 구분하며 외부 처리 결과가 불명확하면 UNKNOWN으로 표현한다.
// 상태 의미는 billing AGENTS.md 11장(환전)을 따른다. 신청·취소는 #285, 관리자 승인·거절은 #294, 송금 실행·결과 반영은 #304.
public enum ExchangeStatus {
    /** 환전 신청. 신청한 수익 HP를 보류하고 관리자 승인을 기다린다. 회원이 취소할 수 있다 */
    REQUESTED,
    /** 관리자 승인(#294). 보류를 유지한 채 정산일 송금을 기다린다. 회원이 취소할 수 없다 */
    APPROVED,
    /** 관리자 거절(#294). 보류한 수익 HP를 전부 수익 HP로 반환했다 */
    REJECTED,
    /** 송금 시도를 저장했고(송금 전·후) 결과를 기다린다. 보류를 유지한다 (#304) */
    PROCESSING,
    /** 송금 성공. 보류한 수익 HP를 확정 차감했다 (#304) */
    COMPLETED,
    /** 마지막 송금 시도가 확정 실패했다. 보류한 수익 HP를 반환하지 않고 유지하며 관리자 판단(수동 재송금 또는 최종 실패)을 기다린다.
     *  자동으로 다시 보내지 않는다 (#304) */
    FAILED,
    /** 관리자가 재송금하지 않고 최종 실패로 종료했다. 보류한 수익 HP를 전부 수익 HP로 반환했다. 다시 송금·확정 차감하지 않는다 (#304) */
    FINAL_FAILED,
    /** 송금 결과가 불명확하거나 운영자 확인이 필요하다. 보류를 유지한다 (#304) */
    UNKNOWN,
    /** 관리자 승인 전(REQUESTED) 회원이 취소했다. 보류한 수익 HP를 전부 반환했다 */
    CANCELED
}
