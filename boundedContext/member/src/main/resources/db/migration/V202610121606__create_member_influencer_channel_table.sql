create table members.influencer_channel
(
    id                  BIGINT generated by default as identity not null,
    user_id             BIGINT                                  not null,
    platform            VARCHAR(255)                            not null,
    channel_identifier  VARCHAR(255)                            not null,
    channel_name        VARCHAR(255)                            not null,
    channel_url         VARCHAR(255)                            not null,
    follower_count      INTEGER                                 not null,
    verification_status VARCHAR(255)                            not null,
    requested_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    verified_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    verified_by         BIGINT,
    rejection_reason    TEXT,
    deleted_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at          TIMESTAMP(6) WITHOUT TIME ZONE,
    constraint pk_influencer_channel primary key (id),
    constraint uc_influencer_channel_platform_channel_identifier unique (platform, channel_identifier)
);

alter table members.influencer_channel
    add constraint FK_INFLUENCER_CHANNEL_ON_USER foreign key (user_id) references members.users (id);
