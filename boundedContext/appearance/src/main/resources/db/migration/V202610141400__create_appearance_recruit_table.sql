-- 출연 모집글: 호스트가 여러 게스트를 공개 모집하는 글 (1:N).
-- host_id는 회원 ID 그대로다 (회원 테이블에 FK를 걸지 않는다).
create table appearances.recruits
(
    id               BIGINT generated by default as identity not null,
    host_id          BIGINT                                  not null,
    title            VARCHAR(100)                            not null,
    host_channel_url VARCHAR(255)                            not null,
    scheduled_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    expected_minutes INTEGER                                 not null,
    content          TEXT                                    not null,
    fee_per_person   BIGINT                                  not null,
    recruit_count    INTEGER                                 not null,
    selected_count   INTEGER                                 not null,
    recruit_deadline TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    status           VARCHAR(255)                            not null,
    -- 아래 세 컬럼은 모집 마감·모집 취소 처리에서 채운다
    close_type       VARCHAR(255),
    closed_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    canceled_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    version          BIGINT                                  not null,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearance_recruits primary key (id),
    constraint ck_appearance_recruits_fee_per_person check (fee_per_person > 0),
    constraint ck_appearance_recruits_recruit_count check (recruit_count > 0),
    constraint ck_appearance_recruits_selected_count check (selected_count between 0 and recruit_count),
    constraint ck_appearance_recruits_expected_minutes check (expected_minutes > 0),
    constraint ck_appearance_recruits_deadline check (recruit_deadline < scheduled_at)
);

-- 모집 중인 모집글 공개 목록 (상태 + 최신순)
create index idx_appearance_recruits_status_created_at on appearances.recruits (status, created_at);
-- 내가 올린 모집글 목록 (호스트)
create index idx_appearance_recruits_host_id_created_at on appearances.recruits (host_id, created_at);
