-- 출연 요청서: 호스트가 게스트 1명에게 보내는 출연 요청 (1:1).
-- host_id, guest_id는 회원 ID 그대로다 (회원 테이블에 FK를 걸지 않는다).
create table appearances.requests
(
    id               BIGINT generated by default as identity not null,
    host_id          BIGINT                                  not null,
    guest_id         BIGINT                                  not null,
    title            VARCHAR(100)                            not null,
    host_channel_url VARCHAR(255)                            not null,
    scheduled_at     TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    expected_minutes INTEGER                                 not null,
    content          TEXT                                    not null,
    fee              BIGINT                                  not null,
    accept_deadline  TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    status           VARCHAR(255)                            not null,
    -- 아래 세 컬럼은 게스트 응답·만료·취소 처리에서 채운다
    reject_reason    VARCHAR(500),
    responded_at     TIMESTAMP(6) WITHOUT TIME ZONE,
    canceled_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    version          BIGINT                                  not null,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE          not null,
    constraint pk_appearance_requests primary key (id),
    constraint ck_appearance_requests_not_self check (host_id <> guest_id),
    constraint ck_appearance_requests_fee check (fee > 0),
    constraint ck_appearance_requests_expected_minutes check (expected_minutes > 0),
    constraint ck_appearance_requests_deadline check (accept_deadline < scheduled_at)
);

-- 출연이 성립하기 전까지 같은 호스트가 같은 게스트에게 보낼 수 있는 요청은 1건이다.
-- 보류 처리 중(HOLD_PENDING)이거나 응답 대기 중(REQUESTED)인 요청서만 묶어, 동시에 들어온 요청도 DB에서 막는다.
create unique index uk_appearance_requests_pending_host_guest
    on appearances.requests (host_id, guest_id)
    where status in ('HOLD_PENDING', 'REQUESTED');

-- 보낸 요청 목록(호스트), 받은 요청 목록(게스트) 조회
create index idx_appearance_requests_host_id_created_at on appearances.requests (host_id, created_at);
create index idx_appearance_requests_guest_id_created_at on appearances.requests (guest_id, created_at);
